"""Справочники из libs/data — по пути ОТ САМИХ СЕБЯ (спринт 144).

ЗАЧЕМ. Снимки констант OpenDota (герои, цены предметов, id предметов)
лежат в `libs/data`, и четыре модуля искали их, отсчитывая каталоги
вверх от собственного файла:

    apps/data-collector/src/collector/signals.py    parents[4]
    apps/feature-extractor/src/extractor/timings.py parents[4]
    apps/report-generator/src/reportgen/builder.py  parents[4] и parents[2]
    apps/draft/src/serve_draft.py                   parents[3] и parents[1]

Число подогнано под раскладку монорепо: от `.../apps/<svc>/src/<pkg>/x.py`
до корня ровно четыре шага. В образе раскладка другая — `/app/src/<pkg>/x.py`,
и четвёртого шага там просто нет: `Path.parents[4]` бросает IndexError.

Проявлялось это тремя разными способами, и хуже всего — третьим:

  ОТКАЗ ГРОМКИЙ. Семь коллекторов и report-generator падали на импорте
  модуля и перезапускались по кругу (VPS, 2026-08-18).

  ОТКАЗ ТИХИЙ. В timings.py то же выражение стояло внутри `try/except
  Exception`, написанного на случай «файла нет». IndexError он ловил
  наравне с остальным, и feature-extractor поднимался УСПЕШНО — с пустым
  справочником предметов. Все покупки писались бы как `item_<id>`.

  ПОЧИНКА, КОТОРАЯ НЕ РАБОТАЕТ. В builder.py кандидаты перебирались:
  сначала путь монорепо, потом путь образа, а цикл ловил и OSError, и
  IndexError. Но исключение бросал не цикл, а СБОРКА СПИСКА — до первой
  попытки. Комментарий над ним честно описывал обе раскладки; код их не
  поддерживал.

ЧТО ЗДЕСЬ. Каталог `data` — сосед этого файла в ЛЮБОЙ раскладке: и в
монорепо (`<root>/libs/`), и в образе (`/app/libs/`), потому что образы
копируют `libs/` целиком. Значит, считать его надо не от вызывающего
модуля, а отсюда — и тогда считать нечего вовсе.

Правило простое: путь к общим данным не вычисляется по месту. Оно
проверяется тестом scripts/tests/test_libs_packaging.py, который считает
глубину каждого `parents[N]` в раскладке ОБРАЗА, а не монорепо.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

# Сосед этого файла. Переопределяется MANTA_DATA_DIR — не для гибкости, а
# ради одного случая: справочник обновляют снимком (tools/refresh-*.py) и
# хотят прогнать сервис на новом, не пересобирая образ.
DATA_DIR = Path(os.getenv("MANTA_DATA_DIR") or Path(__file__).resolve().parent / "data")


def data_path(name: str) -> Path:
    """Путь к файлу справочника. Существование не проверяется."""
    return DATA_DIR / name


def load_json(name: str, default: Any) -> Any:
    """Прочитать справочник; при любой беде вернуть `default`.

    Справочники опциональны СОЗНАТЕЛЬНО: без цен предметов diff-фича
    выродится, но матч всё равно разберётся. Ронять сбор из-за снимка
    констант — хуже, чем считать его неполно.

    Но «опционально» относится только к ФАЙЛУ. Ошибку в вычислении пути
    этот except раньше глотал наравне с отсутствием файла, и поломка
    выглядела как «справочник не завезли». Теперь вычислять нечего.
    """
    try:
        return json.loads(data_path(name).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default
