"""Единая система координат карты Dota — общий контракт (спринт 139).

ЗАЧЕМ. Координаты карты в проекте задавались ТРИЖДЫ и по-разному:

    apps/feature-extractor/.../mapcells.py   MAP_HALF = 8000      мировые
    apps/feature-extractor/.../features.py   MAP_HALF_DIAG = 8000 мировые
    apps/data-collector/.../signals.py       64..192              клетки OpenDota

Пока каждая карта рисовалась своей самодельной схемой, расхождение было
незаметно. Как только под ними появляется ОБЩАЯ подложка, оно становится
видно глазом: тепловые пятна лягут в одном месте, варды — в другом.

И одно из трёх значений заведомо неверно. Комментарий в mapcells.py
говорит, что 8000 взято «совпадает с MAP_HALF_DIAG», но половина СТОРОНЫ
и половина ДИАГОНАЛИ — разные величины, отличающиеся в √2 раз. Либо
позиционные фичи нормируются на сторону, называя её диагональю, либо
тепловая карта режется по диагонали, считая её стороной. Разобраться
можно только замером: см. tools/map-calibrate.py.

ЧТО ЗДЕСЬ. Ровно одно место, где живут границы и переводы. Все карты —
тепловая, вардов, смертей — обязаны считать через него, иначе разойдутся
снова, и снова незаметно.

ПРОСТРАНСТВА КООРДИНАТ. Их три, и путать их дорого:

  МИРОВЫЕ      что отдаёт парсер реплеев: x, y в игровых единицах,
               (0,0) — центр карты, ось Y вверх.
  КЛЕТКИ       что отдаёт OpenDota в obs_log/sen_log: 64..192,
               (0,0) — юго-запад. Один шаг клетки = UNITS_PER_CELL.
  ЕДИНИЧНЫЕ    [0,1]×[0,1] для отрисовки, (0,0) — ЮГО-ЗАПАД (база
               Radiant). SVG рисует сверху вниз, поэтому переворот оси Y
               делается ОДИН раз, в компоненте, а не размазывается по
               коду. Ровно на этом переворачивании карта получается
               правдоподобной, но зеркальной — заметить можно только
               зная, где обычно фармят.
"""
from __future__ import annotations

# Половина СТОРОНЫ проходимой карты в мировых единицах.
#
# ВНИМАНИЕ: значение предварительное и подлежит проверке замером
# (make map-calibrate) на живых данных. 8192 = 2^13 — то, к чему сходятся
# сторонние инструменты и что согласуется с сеткой клеток OpenDota:
# 128 клеток по 128 единиц дают ровно 16384 = 2 × 8192.
#
# Прежнее значение 8000 в mapcells.py пришло из MAP_HALF_DIAG, то есть из
# нормировки ДИАГОНАЛИ, и как половина стороны оно ниоткуда не следует.
WORLD_HALF = 8192.0

# Границы клеточных координат OpenDota для проходимой части карты.
CELL_MIN, CELL_MAX = 64, 192

# Мировых единиц в одной клетке OpenDota. Выводится, а не задаётся: если
# однажды поменяется WORLD_HALF, шаг клетки обязан поменяться вместе с
# ним, иначе два пространства разъедутся молча.
UNITS_PER_CELL = (2.0 * WORLD_HALF) / (CELL_MAX - CELL_MIN)


def cell_to_world(c: float) -> float:
    """Клетка OpenDota → мировая координата."""
    return (float(c) - (CELL_MIN + CELL_MAX) / 2.0) * UNITS_PER_CELL


def world_to_cell(w: float) -> float:
    """Мировая координата → клетка OpenDota."""
    return float(w) / UNITS_PER_CELL + (CELL_MIN + CELL_MAX) / 2.0


def world_to_unit(x: float, y: float) -> tuple[float, float]:
    """Мировые координаты → единичный квадрат [0,1], (0,0) на юго-западе.

    За границами карты значения выходят за [0,1] и НЕ обрезаются: обрезка
    здесь превратила бы «точка вне карты» в «точка на краю карты», а это
    разные факты. Отсеивать негодные позиции должен вызывающий — он
    знает, ошибка это или сознательный выход за пределы.
    """
    return ((float(x) + WORLD_HALF) / (2.0 * WORLD_HALF),
            (float(y) + WORLD_HALF) / (2.0 * WORLD_HALF))


def cell_to_unit(cx: float, cy: float) -> tuple[float, float]:
    """Клетки OpenDota → единичный квадрат."""
    span = float(CELL_MAX - CELL_MIN)
    return ((float(cx) - CELL_MIN) / span, (float(cy) - CELL_MIN) / span)


def unit_to_grid(u: float, v: float, grid: int) -> tuple[int, int]:
    """Единичный квадрат → индексы клетки сетки grid×grid.

    Верхняя граница включается в последнюю клетку, а не создаёт
    (grid+1)-ю: точка ровно на краю карты — законная точка карты.
    """
    gx = min(int(u * grid), grid - 1)
    gy = min(int(v * grid), grid - 1)
    return max(gx, 0), max(gy, 0)


def in_bounds(x: float, y: float) -> bool:
    """Мировая точка внутри проходимой карты."""
    return abs(float(x)) <= WORLD_HALF and abs(float(y)) <= WORLD_HALF
