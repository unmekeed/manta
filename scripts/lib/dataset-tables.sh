#!/usr/bin/env bash
# Что переносится между машинами — ОДИН список на весь проект (спринт 156).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Списков было три, и жили они в разных скриптах:
# dataset-sync.sh знал, что выгружать, backup-drill.sh — что сверять после
# восстановления. Совпадать они обязаны, а сверялись только глазами. К
# спринту 149 списки ClickHouse разошлись трижды подряд (MatchDraft и
# MatchEvents в 76, MatchMapCells в 98, MatchMapCellsMinute в 147), и
# каждый раз слепок молча терял данные, которые из сырья не восстановить.
#
# Тест scripts/tests/test_dataset_sync_covers_schema.py сверяет эти списки
# с миграциями: новая таблица обязана быть либо в переносе, либо в явном
# списке пропуска — и тогда рядом придётся написать причину.
#
# Файл только объявляет; ничего не выполняет и безопасен для source.

# -- ClickHouse ---------------------------------------------------------------
#
# ReplacingMergeTree: повторная вставка дедуплицируется движком, поэтому
# импорт идёт как есть.
#
# MatchFights (спринт 84), MatchMapCells (98) и MatchMapCellsMinute (147)
# переносятся ОБЯЗАТЕЛЬНО: они собираются из ReplayEvents, а он живёт 14
# дней по TTL, реплеи же Valve удаляет сама. Потерять их в слепке значит
# потерять безвозвратно — в отличие от витрин, которые пересчитываются из
# сырья.
#
# Витрины выделены отдельно не для переноса (переносятся они так же), а
# для отчётности: у них своя строка в ежедневном отчёте, и в разделе
# «сопутствующие таблицы» они были бы вторым упоминанием того же.
MART_TABLES=(MatchTimelineFeatures PlayerMatchFeatures)
REPLACING_TABLES=("${MART_TABLES[@]}"
                  MatchDraft MatchEvents MatchFights MatchMapCells
                  MatchMapCellsMinute MatchHeroTimings)

# MergeTree: движок не дедуплицирует, поэтому импорт вливает только новые
# match_id через staging-таблицу. SKIP_RAW=1 — пропустить (архив меньше).
RAW_TABLES=(EconomyTimeline PositionSnapshots)

# Не переносится осознанно: ReplayEvents — сырьё с TTL 14 дней и десятками
# тысяч строк на матч. Всё, что из него нужно, уже посчитано в агрегатах
# выше, а тащить его в слепок значило бы раздуть архив на порядок ради
# данных, которые на принимающей машине протухнут через две недели.
SKIPPED_TABLES=(ReplayEvents)

# Всё, кроме витрин, — для ежедневного отчёта: витрины он показывает
# отдельной строкой, остальные таблицы перечисляет числом матчей. Список
# у отчёта был свой и уже разъехался: MatchMapCellsMinute появилась в
# спринте 147 и в отчёт не попала.
companion_tables() {
    local t m skip
    for t in "${REPLACING_TABLES[@]}" "${RAW_TABLES[@]}" "${SKIPPED_TABLES[@]}"; do
        skip=""
        for m in "${MART_TABLES[@]}"; do [ "$t" = "$m" ] && skip=1; done
        [ -n "$skip" ] || printf '%s\n' "$t"
    done
}

# -- PostgreSQL ---------------------------------------------------------------
#
# Тот же принцип и та же цена ошибки — но сюда её принесли на семь
# спринтов позже. До спринта 156 список Postgres был не списком, а двумя
# строками кода, и проверка покрытия его не видела вовсе: она сверяла со
# схемой только ClickHouse.
#
# Стоило это ровно того, чего и следовало ждать. PlayerRanks — кэш рангов,
# который наполняется квотой OpenDota (2000 запросов в сутки, купить
# больше нельзя) и накапливается неделями. Он НЕ переносился. Свежая
# машина получала полный слепок витрин и пустой кэш рангов, отбор
# кандидатов на ней не находил ни одного матча, и выглядело это как
# «очередь почему-то пустая», а не как «мы забыли перенести таблицу».
#
# Имена ЗДЕСЬ В НИЖНЕМ РЕГИСТРЕ, потому что так они и лежат в Postgres:
# CREATE TABLE PlayerRanks заводит таблицу playerranks. Сверка со схемой
# это учитывает.
#
# replaysalts переносится по той же причине, что и playerranks: это не
# производная витрина, а НАКОПЛЕННЫЙ дефицитный ресурс. Соль знает только
# Game Coordinator, и отдаёт он их порядка 200–400 в сутки на аккаунт
# (спринт 171). Не перенести таблицу — значит выбросить недели добычи и
# заново потратить бюджет на то, что уже добыто.
PG_TABLES=(collectedmatches matchreports playerranks
           replaycandidates parkedreplays replaysalts)

# Пропускается осознанно, по трём разным причинам:
#
#   машинно-специфичное состояние — переносить не просто бесполезно, а
#   вредно. collectorcursor: позиция в потоке Valve у каждой машины своя,
#   и чужая отбросила бы сбор назад или вперёд. apibudget: суточный счёт
#   вызовов OpenDota считается НА IP; втянув чужой расход, машина решила
#   бы, что квота уже потрачена, и молча перестала собирать.
#
#   состояние запроса пользователя, а не датасет — eventoutbox (транзакт-
#   ционный outbox, строки уходят после публикации) и analysisjobs
#   (задания шлюза на разбор загруженного реплея).
#
#   мёртвая схема из миграции 001 — players, accounts, tournaments,
#   matches, matchplayers, subscriptions. Заведены первым эскизом и с тех
#   пор в код не попали ни разу (проверено поиском по INSERT/SELECT).
#   Пустые таблицы переносить нечего; удалить их — отдельный разговор, и
#   молчаливо это делать нельзя.
PG_SKIPPED_TABLES=(collectorcursor apibudget eventoutbox analysisjobs
                   players accounts tournaments matches matchplayers
                   subscriptions)

# -- правила слияния ----------------------------------------------------------
#
# Слепок вливается в ЖИВУЮ базу, где уже что-то есть. Что делать при
# совпадении ключа — решение про смысл таблицы, а не про синтаксис, и у
# каждой оно своё.
#
# Списка колонок здесь намеренно нет: он приходит из архива. Рукописный
# перечень колонок — та же беда, что рукописный перечень таблиц, только
# незаметнее: новая колонка просто перестала бы обновляться при слиянии,
# а выглядело бы это как «отчёт не обновился».

# _set_all <таблица> <колонки> <ключ> → «a = EXCLUDED.a, b = EXCLUDED.b»
_set_all() {
    local key="$3" out="" c
    local IFS=,
    for c in $2; do
        [ "$c" = "$key" ] && continue
        out="${out:+$out, }$c = EXCLUDED.$c"
    done
    printf '%s' "$out"
}

# _set_ranks <колонки> — слияние кэша рангов.
#
# Три разных правила на три вида колонок, и каждое отвечает на свой
# вопрос:
#
#   checked_at/seen_at/seen_count — GREATEST. Счётчик встреч это ПРИОРИТЕТ
#     опроса, а не статистика: суммировать его нельзя, потому что обе
#     машины идут по ОДНОМУ потоку Valve и видят одни и те же матчи —
#     сумма надула бы приоритет вдвое на ровном месте. «Не меньше, чем
#     видела любая из машин» — честный ответ.
#
#   всё остальное (rank_tier, source и любая будущая колонка) — побеждает
#     тот, кто спрашивал ПОЗЖЕ. Ранг меняется неделями, свежий ответ
#     вернее старого.
#
#   и главное: строка, которую никто не спрашивал (checked_at IS NULL),
#     не затирает известный ранг. Без этого условия встреча аккаунта в
#     потоке на второй машине — событие, не стоившее ни одного запроса, —
#     стирала бы ранг, за который заплачено квотой.
_set_ranks() {
    local fresher="EXCLUDED.checked_at IS NOT NULL AND (playerranks.checked_at IS NULL OR EXCLUDED.checked_at > playerranks.checked_at)"
    local out="" c
    local IFS=,
    for c in $1; do
        case "$c" in
            account_id) continue;;
            checked_at|seen_at|seen_count)
                out="${out:+$out, }$c = GREATEST(playerranks.$c, EXCLUDED.$c)";;
            *)
                out="${out:+$out, }$c = CASE WHEN $fresher THEN EXCLUDED.$c ELSE playerranks.$c END";;
        esac
    done
    printf '%s' "$out"
}

has_column() { case ",$2," in *",$1,"*) return 0;; *) return 1;; esac; }
count_columns() { awk -F, '{print NF}' <<<"$1"; }

# csv_field_count <файл.csv.gz> → сколько полей в первой записи (или пусто)
#
# Нужно для архивов, снятых ДО спринта 156: списка колонок они не несут, и
# без него единственный способ понять, сколько их было, — посмотреть в сам
# CSV. Именно csv-разбором, а не подсчётом запятых: в matchreports лежат
# два JSONB, и запятых внутри одного поля там больше, чем полей.
#
# Пусто в ответе — не беда, а «не смог»: у вызывающего есть запасной путь.
csv_field_count() {
    command -v python3 >/dev/null 2>&1 || return 0
    python3 - "$1" <<'PY' 2>/dev/null || return 0
import csv, gzip, sys
csv.field_size_limit(1 << 30)          # analysis JSONB не влезает в умолчание
try:
    print(len(next(csv.reader(gzip.open(sys.argv[1], "rt", newline="")))))
except (OSError, ValueError, StopIteration):
    sys.exit(1)
PY
}

# archive_columns <колонки схемы> <сколько в архиве> → колонки архива
#
# Опирается на то, что миграции колонки только ДОБАВЛЯЮТ (ALTER TABLE ADD
# COLUMN в конец), поэтому старая схема — это префикс новой. За всю
# историю проекта иначе и не было: 009 добавила три колонки
# ReplayCandidates, 012 — одну CollectedMatches. Появись когда-нибудь
# DROP COLUMN или переименование — допущение сломается, и вместе с ним
# сломается импорт СТАРЫХ архивов; новые несут свой список и не зависят
# от этого вовсе.
archive_columns() {
    local total; total=$(count_columns "$1")
    [ "$2" -le "$total" ] 2>/dev/null || return 1
    cut -d, -f"1-$2" <<<"$1"
}

# -- совместимость со старыми архивами ----------------------------------------
#
# Слепок несёт список своих колонок, и он может отличаться от текущей
# схемы: две машины почти никогда не стоят на одном коммите. Обычно
# разницу закрывает DEFAULT — но не всегда, и миграция 012 ровно такой
# случай.
#
# has_replay значит «данные реплея у нас есть». В архиве до миграции этой
# колонки нет, DEFAULT у неё FALSE, и импорт объявил бы все собранные
# реплеи несобранными — принимающая машина пошла бы качать их заново, по
# 58 МиБ штука. Сама миграция признак ВОССТАНАВЛИВАЕТ из replay_url
# (json: — это таймлайн, всё остальное — реплей); импорт делает то же
# самое и тем же правилом.

# pg_backfill_sql <таблица> <колонки архива> <временная таблица>
# → SQL, восстанавливающий недостающие колонки, или пусто
pg_backfill_sql() {
    if [ "$1" = collectedmatches ] && ! has_column has_replay "$2"; then
        printf "UPDATE %s SET has_replay = (replay_url NOT LIKE 'json:%%');" "$3"
    fi
}

# pg_insert_cols <таблица> <колонки архива> → колонки для INSERT
#
# Отличается от колонок COPY, и путать их нельзя: в CollectedMatches
# has_replay объявлена ПОСЛЕДНЕЙ, так что «отрезать хвост перед COPY»
# отрезало бы и настоящую колонку из свежего архива.
pg_insert_cols() {
    if [ "$1" = collectedmatches ] && ! has_column has_replay "$2"; then
        printf '%s,has_replay' "$2"
    else
        printf '%s' "$2"
    fi
}

# pg_merge_sql <таблица> <колонки-через-запятую> → хвост ON CONFLICT
pg_merge_sql() {
    case "$1" in
        collectedmatches)
            # Повышение, но никогда понижение — то же правило, что у
            # коллектора в _mark_collected. has_replay значит «данные
            # реплея у нас есть»; сам файл не переносится, но ВСЁ, что из
            # него посчитано (MatchEvents, MatchFights, карты), в слепке
            # есть. Оставь тут DO NOTHING — принимающая машина полезла бы
            # качать 58 МиБ ради данных, которые только что втянула.
            printf 'ON CONFLICT (match_id) DO UPDATE SET has_replay = collectedmatches.has_replay OR EXCLUDED.has_replay'
            ;;
        matchreports)
            # Отчёт перегенерируется целиком, поэтому побеждает более
            # свежий — но именно более свежий, а не последний пришедший:
            # порядок слияния слепков произволен.
            printf 'ON CONFLICT (match_id) DO UPDATE SET %s WHERE EXCLUDED.generated_at > matchreports.generated_at' \
                   "$(_set_all matchreports "$2" match_id)"
            ;;
        playerranks)
            printf 'ON CONFLICT (account_id) DO UPDATE SET %s' "$(_set_ranks "$2")"
            ;;
        replaysalts)
            # Соль матча неизменна: её выдал GC, и второй раз он выдаст
            # ту же. Значит спорить не о чем — но и перезаписывать нечем,
            # а DO NOTHING заодно бережёт свой found_at, по которому
            # видно, когда добыто.
            printf 'ON CONFLICT (match_id) DO NOTHING'
            ;;
        replaycandidates|parkedreplays)
            # Ценность строки — сам факт «этот матч стоит скачать» (её
            # добыли квотой). Состояние — state, attempts, host — знание
            # МЕСТНОЕ: чужое «taken» или «failed» здесь означало бы
            # неправду о своей же очереди.
            printf 'ON CONFLICT (match_id) DO NOTHING'
            ;;
        *)
            printf 'ОШИБКА: нет правила слияния для таблицы %s\n' "$1" >&2
            return 1
            ;;
    esac
}
