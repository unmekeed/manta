"""Скрипт частного доступа не заводит новых секретов (спринт 198).

Проверки здесь статические и все — про решения, которые легко принять
наоборот и не заметить последствий.

ГЛАВНОЕ — ключ авторизации. `tailscale up --authkey=...` подключает
машину без браузера, и соблазн вписать его в скрипт велик: установка
становится неинтерактивной. Но ключ password-equivalent, и попав в
скрипт, он попадает в git; попав в переменную окружения — в env-файл и в
историю команд. Ради разовой операции завёлся бы вечный секрет. Ссылка,
которую печатает `tailscale up`, живёт минуты и одноразова.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "tailscale-setup.sh"


def code() -> str:
    """Текст скрипта без комментариев.

    Комментарии выбрасываются, потому что проверяем МЫ КОД, а не
    объяснения рядом с ним. Ровно на этом уже спотыкался тест исключения
    для MLflow в спринте 193a: мутация «убрать условие, оставить
    комментарий» его пережила.
    """
    return "\n".join(line for line in SCRIPT.read_text(encoding="utf-8")
                     .splitlines() if not line.lstrip().startswith("#"))


def test_the_script_exists_and_is_runnable():
    """Страховка от проверки пустоты."""
    assert SCRIPT.exists(), "скрипта нет"
    assert len(code()) > 200, "разбор дал пустой текст — проверки ниже слепы"


def test_no_auth_key_is_ever_passed():
    """ГЛАВНОЕ: ключ авторизации не передаётся и не читается.

    Ни аргументом, ни из окружения. Иначе секрет, нужный один раз,
    остался бы навсегда — в git, в env-файле или в истории команд.
    """
    src = code()
    assert "--authkey" not in src, "ключ авторизации попал в скрипт"
    assert "TS_AUTHKEY" not in src and "TAILSCALE_AUTHKEY" not in src, (
        "скрипт читает ключ из окружения — секрет переезжает в env-файл")


def test_liveness_is_judged_by_the_connection_not_by_the_service():
    """Подключение проверяется у tailscale, а не по запущенному демону.

    Демон прекрасно работает на вылогиненной машине. Считать его
    запуск доступом — это ровно та ошибка, что стоила двух суток на
    STRATZ: контейнер стоял `Up`, отвечал 403 и не собирал ничего.
    Проверять надо пригодность, а не присутствие.
    """
    src = code()
    assert "BackendState" in src, (
        "живость определяется не состоянием подключения — "
        "поднятый демон при вылогиненной машине сойдёт за доступ")
    assert "systemctl is-active" not in src


def test_the_check_mode_does_not_install_anything():
    """`--check` только смотрит: установка идёт ПОСЛЕ выхода из него.

    Диагностическая команда, которая что-то ставит, — это команда,
    которую боятся запускать, а значит не запускают.
    """
    head = code().split('if [ "$CHECK_ONLY" = 1 ]', 1)[0]
    # Ищем ВЫЗОВ, а не упоминание: команда — это начало строки, а не
    # подстрока где угодно. Первая редакция теста падала на подсказке
    # «выполни: sudo tailscale up» внутри сообщения об ошибке — то есть
    # проверяла текст, а не поведение.
    started = [ln.strip() for ln in head.splitlines()
               if ln.strip().startswith(("curl ", "sudo tailscale", "tailscale up"))]
    assert not started, f"до ветки --check выполняются команды: {started}"


def test_the_script_does_not_touch_the_firewall():
    """Порты и ufw не трогаем — этим можно отрезать себе ssh.

    Решение «закрыть 8081 наружу» правильное, но принимать его надо
    глядя на живую машину. Скрипт установки, отрезающий доступ к машине,
    — худший из возможных способов узнать, что правило было неверным.
    """
    src = code()
    for danger in ("ufw ", "iptables", "nft "):
        assert danger not in src, f"скрипт трогает firewall: {danger!r}"


def test_the_report_checks_reachability_instead_of_declaring_it():
    """ГЛАВНОЕ: отчёт ПРОВЕРЯЕТ адреса, а не объявляет их рабочими.

    Первая редакция скрипта печатала список адресов как факт и добавляла,
    что «из частной сети они доступны». Это было неверно: сервисы
    привязаны к 127.0.0.1 — намеренно, `vps-bootstrap` даже стережёт эту
    привязку, — а соединение из сети Tailscale приходит на адрес 100.x и
    до петли не доходит. Список выглядел убедительно и не работал.

    Ровно та форма ошибки, которую проект ловит с июля: смонтированный
    том приняли за используемый, поднятый контейнер — за работающий
    источник, наличие токена — за его пригодность. Здесь то же самое с
    адресом.

    Поэтому отчёт обязан ходить по адресам curl'ом и говорить, что
    ответило. Ошибиться в таком отчёте нельзя: он показывает не намерение
    автора, а состояние машины.
    """
    src = code()
    assert "curl" in src, (
        "отчёт не проверяет достижимость — он снова объявляет её")
    assert "--max-time" in src, (
        "проверка без таймаута повесит диагностическую команду на "
        "недоступном адресе, а её запускают именно тогда, когда что-то "
        "недоступно")
    assert "НЕ отвечает" in src, "недостижимый адрес не отмечается как таковой"


def test_the_report_uses_the_right_scheme_for_each_port():
    """Схема у каждого порта своя, и перепутать их легко.

    Шлюз на 8080 поднимается через `ListenAndServeTLS` — это HTTPS с
    самоподписанным сертификатом. Публичный слой на 8081 — обычный
    `ListenAndServe`, то есть HTTP. Проверка по неверной схеме соединения
    не даст, и отчёт объявит недоступным порт, который работает: ложная
    тревога в инструменте, которому верят.
    """
    src = code()
    assert "https|8080" in src, "8080 проверяется не по HTTPS"
    assert "http|8081" in src, "8081 проверяется не по HTTP"
    assert "curl -sk" in src, (
        "у шлюза самоподписанный сертификат: без -k проверка достижимости "
        "провалится на недоверии, а не на недоступности")
