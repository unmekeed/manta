"""Каждый раздел доктора обязан ЧТО-ТО измерить (спринт 201).

Механическая половина правила «объявление — не факт» (docs/HANDOFF.md).
Всё остальное в нём механизировать не вышло: оно работает поперёк языков
и слоёв. А вот одно проверяемо и стоит проверки — доктор не должен
получить раздел, который лишь читает конфиг и печатает по нему вердикт.

ПОЧЕМУ ИМЕННО ДОКТОР. В нём эта ошибка кучкуется, потому что читать
файлы дёшево, а ходить в живую систему дорого и муторно. Два случая
сентября именно такие:

  * раздел «Тома» проверял, что том ОБЪЯВЛЕН в compose, — а сервис писал
    в /tmp, и том стоял пустым с даты сборки образа (спринт 193);
  * раздел «Квота» брал остаток БЕЗ КЛЮЧА, то есть мерил чужое ведро, и
    показывал успокаивающие 2999 при 1771 потраченном (найдено 07.09).

Оба выглядели как исправные проверки и оба отвечали не на тот вопрос.

ЧЕГО ЭТОТ ТЕСТ НЕ УМЕЕТ. Он не судит, ПРАВИЛЬНОЕ ли измерение делает
раздел: «Квота» ходила в сеть и всё равно мерила не то. Он ловит более
грубую ошибку — раздел, который не наблюдает ничего вовсе.
"""
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
DOCTOR = ROOT / "scripts" / "doctor.sh"

# Команды, которые действительно НАБЛЮДАЮТ систему.
#
# Список закрытый и рукописный: «это команда, трогающая живое» знает
# только человек. Зато каждая строка — проверяемое утверждение, а не
# надежда, и новая форма наблюдения дописывается сюда осознанно.
PROBES = (
    # прямые вызовы
    "docker ", "psql", "clickhouse-client", "curl ", "df ", "ls ",
    "pgrep", "stat ", "wget ",
    # собственные помощники доктора: `ch()` ходит в ClickHouse по HTTP,
    # `$KAFKA_BIN` — это `docker exec` в контейнер Kafka. Без них
    # проверка объявляла бы «ничего не наблюдающими» четыре раздела,
    # которые как раз наблюдают больше прочих.
    "ch \"", "ch '", "$KAFKA_BIN",
)

# Разделы, которым наблюдать нечего, — с ПРИЧИНОЙ у каждого.
#
# Пустой список исключений был бы честнее, но неправдой: сводка в конце
# ничего не измеряет по определению. Всё остальное обязано измерять.
NO_PROBE_OK = {
    # (нет исключений — все разделы что-то измеряют)
}


def sections() -> list[tuple[str, str]]:
    """(заголовок, тело) каждого раздела доктора.

    Раздел начинается с `echo "== ...`; тело — всё до следующего такого
    же или до конца файла.
    """
    src = DOCTOR.read_text(encoding="utf-8")
    marks = list(re.finditer(r'^echo "== (.+?)"', src, re.M))
    out = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(src)
        out.append((m.group(1), src[m.end():end]))
    return out


def test_the_parsing_finds_the_sections():
    """Страховка от проверки пустоты.

    Сломайся разбор — параметризованный тест ниже получил бы пустой
    список и был бы тождественно зелёным. Ровно этот промах уже ловился
    на себе в спринтах 195 и 198.
    """
    got = sections()
    assert len(got) >= 8, [t for t, _ in got]


@pytest.mark.parametrize("title", [t for t, _ in sections()])
def test_every_section_observes_something(title):
    """ГЛАВНОЕ: раздел ходит в живую систему, а не читает конфиг.

    Вердикт, выведенный из настройки, подтверждает НАМЕРЕНИЕ автора
    конфига. Доктор существует, чтобы отвечать на другой вопрос — что
    происходит на машине сейчас.
    """
    if title in NO_PROBE_OK:
        pytest.skip(f"объявлено исключение: {NO_PROBE_OK[title]}")
    body = dict(sections())[title]
    code = "\n".join(ln for ln in body.splitlines()
                     if not ln.lstrip().startswith("#"))
    assert any(p in code for p in PROBES), (
        f"раздел «{title}» ничего не наблюдает — он выносит вердикт по "
        f"тому, что мы сами написали в конфиг. Либо добавить измерение, "
        f"либо вписать раздел в NO_PROBE_OK С ПРИЧИНОЙ")


def test_the_rule_itself_is_written_down():
    """Правило живёт в HANDOFF, а не только в этом тесте.

    Тест ловит одну грубую форму ошибки в одном файле. Само правило
    работает поперёк языков и слоёв, механизировать его не вышло, и
    единственный его носитель — список случаев в документе. Исчезни он —
    останется проверка без объяснения, которую первый же спорящий
    отключит как формальность.
    """
    handoff = (ROOT / "docs" / "HANDOFF.md").read_text(encoding="utf-8")
    assert "## Правило проверок: объявление — не факт" in handoff
    assert "Присутствие ≠ пригодность" in handoff
    assert "Отсутствие ≠ ноль" in handoff


def test_the_case_list_keeps_growing():
    """Список случаев — не иллюстрация, а рабочий материал.

    Он существует, чтобы в него ЗАГЛЯДЫВАЛИ перед тем, как поверить
    очередной проверке. Список, переставший пополняться, превращается в
    историческую справку: новые формы той же ошибки в нём не находятся, и
    смотреть в него перестают.
    """
    handoff = (ROOT / "docs" / "HANDOFF.md").read_text(encoding="utf-8")
    block = handoff.split("## Правило проверок: объявление — не факт", 1)[1]
    block = block.split("\n## ", 1)[0]
    rows = [ln for ln in block.splitlines()
            if ln.startswith("| ") and "---" not in ln]
    assert len(rows) >= 10, (
        f"в списке случаев {len(rows)} строк — он перестал пополняться, "
        f"хотя каждая новая форма этой ошибки стоила простоя")
