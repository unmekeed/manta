"""Наполнитель солей: темп и молчание (спринт 171).

ЧТО ЗДЕСЬ ДОРОГО ОШИБИТЬСЯ. Наполнитель тратит РАСХОДУЕМЫЙ ресурс:
бюджет аккаунта Steam, 200–400 запросов в сутки, и восстанавливается он
не минутами. Ошибка в темпе не падает и не видна в логе — она просто
съедает суточную добычу за один прогон, а расписание потом весь день
ходит впустую.

Вторая половина — про то, КАК GC отказывает. Он не отвечает словами: он
замолкает. То же молчание бывает и при исчерпанном бюджете (штатное
состояние, каждую ночь), и при разрыве сессии (настоящая беда). Спутать
их в сторону тревоги — значит завести ежесуточный ложный алерт, ровно
тот сорт, что вычищали в спринте 163; спутать в сторону тишины — значит
не заметить, что добыча встала.

SQL наполнителя проверяется отдельно и на живой базе
(apps/data-collector/tests/test_replay_salts_sql.py): смысл предиката
фейковым курсором не проверить.
"""
import re
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "gc-node" / "gc-salts.mjs"
SRC = SCRIPT.read_text(encoding="utf-8")


def _loop() -> str:
    """Тело цикла по матчам — там живут и темп, и молчание."""
    return SRC.split("for (const row of rows) {")[1].split("\n  }")[0]


# -- расход бюджета ------------------------------------------------------------

def test_a_run_takes_a_small_portion(tmp_path=None):
    """Порция за прогон — единицы, а не сотни.

    Замер 2026-09-01: бюджет НАКОПИТЕЛЬНЫЙ. Первые 200 запросов прошли
    подряд, потому что накопитель был полон за месяцы простоя; дальше
    аккаунт отдавал около 0.3 соли в минуту. Прогон, берущий много за
    раз, опустошит накопитель и оставит расписание ни с чем до
    следующего наполнения.
    """
    per_run = int(re.search(r"GC_SALTS_PER_RUN \|\| (\d+)", SRC).group(1))
    assert 1 <= per_run <= 20, (
        f"порция {per_run} слишком велика для суточного бюджета 200–400")


def test_the_portion_size_reaches_the_query(tmp_path=None):
    """Порция ограничивает ВЫБОРКУ, а не только цикл.

    Ограничить один цикл значило бы вытащить из базы всё и отбросить
    лишнее — на глаз то же самое, но предел перестал бы быть пределом,
    стоит появиться второму месту, читающему ту же выборку.
    """
    assert "LIMIT $1" in SRC
    assert "db.query(PICK_SQL, [Math.min(PER_RUN, left)])" in SRC


def test_there_is_a_pause_between_requests():
    """Пауза между запросами есть и настраивается.

    Темп оказался ни при чём для БЮДЖЕТА, но пауза остаётся: она делает
    прогон прерываемым и не даёт наполнителю выглядеть как всплеск
    трафика со стороны Valve.
    """
    assert "GC_SALTS_DELAY_MS" in SRC
    assert "await sleep(DELAY_MS);" in _loop()


def test_the_pause_follows_every_answer_not_only_a_saved_salt():
    """Пауза после ЛЮБОГО ответа.

    ПОЙМАНО ПРИ НАПИСАНИИ ТЕСТА. Пауза стояла только в ветке удачного
    сохранения, а матч без соли уходил дальше сразу же — при том, что
    единицу бюджета съедает сам запрос, а не ответ. Порция из восьми
    матчей без солей отработала бы залпом.
    """
    loop = _loop()
    # Проверять надо ВЛОЖЕННОСТЬ, а не порядок строк. Мутация «перенести
    # паузу внутрь удачной ветки» не меняет порядок ни на строку, и
    # проверка «noSalt++ раньше sleep» её пропускала — поймано мутацией.
    # Отступ различает их однозначно: тело цикла на четырёх пробелах,
    # тело ветки — на шести.
    assert re.search(r"^    await sleep\(DELAY_MS\);$", loop, re.M), (
        "пауза вложена в ветку: матч без соли проскакивает её, "
        "хотя стоил той же единицы бюджета")


# -- молчание ------------------------------------------------------------------

def test_silence_ends_the_run_calmly():
    """Исчерпанный бюджет — штатный конец, а не отказ.

    Наполнитель по расписанию ДОЛЖЕН упираться в бюджет: это признак
    того, что он его выбирает целиком. Ненулевой код возврата здесь
    означал бы письмо в Telegram каждую ночь — и через неделю на алерты
    перестали бы смотреть.
    """
    loop = _loop()
    tail = loop.split("if (silent >= SILENCE_LIMIT)")[1]
    assert "бюджет на сегодня" in tail
    assert "break;" in tail
    # Именно console.log, а не console.error: разбор логов делит потоки.
    assert "console.error" not in tail.split("break;")[0]
    # После цикла — выход нулём.
    after = SRC.split("console.log(`соли: спрошено")[1]
    assert "finish(0)" in after


def test_a_dead_session_is_still_an_error():
    """А вот не поднявшаяся сессия — беда, и молчать о ней нельзя.

    Отличие от бюджета в том, что тут не отвечает не GC, а вход: соли
    не будет ни сегодня, ни завтра, и чинить надо руками (токен, CM,
    сеть). Уравняй эти два случая — и остановка добычи выглядела бы как
    обычная ночь.
    """
    # Якорь — строка ожидания сессии: `if (!ready) {` в файле не одна,
    # вторая живёт внутри waitForGC.
    block = SRC.split("const ready = await waitForGC();")[1].split("\n\n")[0]
    assert "finish(1)" in block, "мёртвая сессия должна отличаться кодом"
    assert "console.error" in block


def test_silence_is_bounded_but_not_hair_trigger():
    """Молчаний до остановки — больше одного и немного.

    Один таймаут бывает случайным: порция обрывалась бы на первой же
    задержке сети, и суточная добыча падала бы кратно. Много — трата
    времени расписания: бюджет не восстанавливается за минуты, это
    проверено пятиминутными передышками в замере.
    """
    limit = int(re.search(r"GC_SALTS_SILENCE_LIMIT \|\| (\d+)", SRC).group(1))
    assert 2 <= limit <= 5, f"порог молчания {limit} вне разумного"


def test_an_answer_clears_the_accumulated_silence():
    """Молчания считаются ПОДРЯД, а не за прогон.

    ПОЙМАНО ПРИ НАПИСАНИИ ТЕСТА. Счётчик обнулялся только после
    сохранённой соли, так что два разрозненных таймаута посреди
    исправной работы обрывали порцию — и выглядело бы это как
    «бюджет кончился», хотя GC отвечал.
    """
    loop = _loop()
    # Обнуление стоит после развилки «ответ пришёл», до разбора ответа, —
    # то есть его получает и ответ без соли.
    assert loop.index("silent = 0;") < loop.index("noSalt++"), (
        "ответ без соли не сбрасывает счётчик молчаний")


def test_a_request_cannot_hang_forever():
    """У запроса есть таймаут.

    GC замолкает без разрыва соединения. Без таймаута наполнитель
    висел бы до убийства по cron'у — ровно та беда, что была у
    питоновского входа: процесс жив, ответа нет, причина неизвестна.
    """
    assert re.search(r"function requestDetails\(matchId, timeoutMs = \d+\)", SRC)
    assert "resolve(null);                       // молчание" in SRC


# -- что попадает в базу -------------------------------------------------------

def test_a_zero_salt_is_not_mistaken_for_a_missing_one():
    """Соль 0 — значение, а не отсутствие.

    Проверка на истинность (`!m.replay_salt`) выбросила бы её как
    пустую. Вероятность мала, но цена ошибки — матч, навсегда
    помеченный «соли нет», при том что соль была.
    """
    assert "m.replay_salt == null" in SRC
    assert "!m.replay_salt" not in SRC


def test_the_match_id_saved_is_the_one_gc_answered():
    """В базу пишется id ИЗ ОТВЕТА, а не из запроса.

    Ответ GC на чужой запрос теоретически возможен (сообщения не
    связаны идентификатором), и записать чужую соль под наш id значило
    бы отравить очередь скачивания: ссылка соберётся, файл не
    скачается, и виноватой будет выглядеть Valve.
    """
    save = SRC.split("await db.query(SAVE_SQL,")[1].split(")")[0]
    assert "m.match_id" in save, "сохраняется не тот id, что прислал GC"


# -- секрет --------------------------------------------------------------------

def test_the_token_is_never_printed():
    """Токен обновления равносилен паролю и в вывод не попадает.

    Наполнитель ходит по расписанию, его вывод уезжает в лог и в
    Telegram. Одна отладочная строка — и токен лежит в переписке
    навсегда.
    """
    # Искать слово «token» нельзя: так называется и файл
    # (`refresh-token`), и цель `make gc-token`. Опасна именно
    # ПЕРЕМЕННАЯ token — в подстановке или аргументом.
    leak = re.compile(r"\$\{\s*token\b|\btoken\s*(?:,|\)|\.slice|\.substring)")
    for line in SRC.splitlines():
        if "console." in line:
            assert not leak.search(line), f"токен в выводе: {line.strip()}"


def test_a_missing_token_says_what_to_do():
    """Без токена — понятный отказ с командой.

    «Cannot read properties of undefined» на третий месяц эксплуатации
    стоит владельцу получаса; строчка с именем цели — нисколько.
    """
    assert "make gc-token" in SRC
    # До конца блока, а не до первой `}`: в сообщении есть `${stateDir}`,
    # и наивная нарезка обрывала бы проверку прямо перед подсказкой.
    block = SRC.split("} catch {")[1].split("\n}")[0]
    assert "make gc-token" in block, "подсказка не в ветке отказа"


# -- учёт бюджета (спринт 173) --------------------------------------------------

def test_spending_counts_requests_not_salts():
    """Считается ВОПРОС, а не удача.

    Единицу бюджета съедает отправленный запрос: матч, у которого соли не
    оказалось, стоил столько же, сколько удачный. Учёт по сохранённым
    солям занижал бы расход — и занижал бы тем сильнее, чем хуже идут
    дела, то есть врал бы именно тогда, когда нужен.
    """
    loop = _loop()
    assert "asked++" in loop
    # До ответа, а не после: молчание в ответ — тоже потраченная единица.
    assert loop.index("asked++") < loop.index("await requestDetails")


def test_spending_is_recorded_even_when_nothing_was_saved():
    """Расход пишется и после неудачной порции.

    Записывать только удачные прогоны значило бы вести учёт, который
    занижает потраченное ровно в тех сутках, когда бюджет и кончился.
    """
    block = SRC.split("if (asked > 0) {")[1].split("}")[0]
    assert "SPEND_SQL" in block
    assert "saved" not in block, "расход зависит от удач"


def test_the_daily_ceiling_stops_the_run_calmly():
    """Выбранный потолок — штатный конец, а не отказ.

    Он наступает каждые сутки, если добыча идёт хорошо. Ненулевой код
    здесь дал бы ежесуточный красный алерт на признак успеха.
    """
    block = SRC.split("if (left <= 0) {")[1].split("\n  }")[0]
    assert "finish(0)" in block
    assert "console.error" not in block


def test_the_portion_shrinks_to_what_is_left():
    """Остаток бюджета урезает порцию, а не отменяет её.

    Обрубить последние три запроса ради круглого числа значило бы
    выбросить три соли даром.
    """
    assert "Math.min(PER_RUN, left)" in SRC


def test_the_ceiling_is_read_before_the_portion_is_picked():
    """Сначала остаток, потом выборка.

    Иначе порция бралась бы полной и урезалась постфактум — то есть
    предел применялся бы к циклу, но не к запросу, и второе место,
    читающее ту же выборку, получило бы лишнее.
    """
    assert SRC.index("const used =") < SRC.index("db.query(PICK_SQL")


def test_the_budget_is_kept_apart_from_the_opendota_one():
    """Свой счёт — под своим именем api.

    Попади расход GC в строки OpenDota, коллекторы решили бы, что квота
    в 2000 выбрана, и остановились бы при нетронутой квоте. Все запросы
    бюджета фильтруют по api, поэтому имя должно быть своим.
    """
    assert "const BUDGET_API = 'steam-gc';" in SRC
    for sql in ("USED_SQL", "SPEND_SQL"):
        body = SRC.split(f"const {sql} = `")[1].split("`;")[0]
        assert "api = $1" in body or "(day, api, source)" in body


def test_the_day_boundary_is_utc():
    """Сутки — UTC, как у OpenDota.

    Две границы суток в одной таблице пришлось бы каждый раз
    вспоминать, а ошибка дала бы «потолок выбран» на час раньше или
    позже — то есть потерянный или удвоенный час добычи.
    """
    for sql in ("USED_SQL", "SPEND_SQL"):
        body = SRC.split(f"const {sql} = `")[1].split("`;")[0]
        assert "AT TIME ZONE 'UTC'" in body, f"{sql} считает сутки не в UTC"
