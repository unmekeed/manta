#!/usr/bin/env bash
# Якорь WSL: держит дистрибутив живым, когда все окна терминала закрыты.
#
# ЗАЧЕМ. Все процессы стека запускаются через nohup (см. dev-recover.sh),
# поэтому SIGHUP при закрытии окна им не страшен. Убивает их не сигнал, а
# сам WSL: когда закрывается ПОСЛЕДНИЙ сеанс дистрибутива, WSL гасит
# виртуальную машину целиком, вместе со всем, что внутри неё работало.
# Поэтому «закрыл окно на крестик» и «остановил сбор» до сих пор было
# одним и тем же действием, и окно приходилось держать открытым.
#
# ЧТО ДЕЛАЕТ. Ровно одно: занимает сеанс, который никто не закрывает.
# Пока живёт этот процесс, у дистрибутива есть хотя бы один сеанс, и WSL
# его не гасит. Никакой работы якорь не выполняет — у него нет ни доступа
# к БД, ни к сети, и сломать он ничего не может.
#
# ЗАПУСК. Из Windows, скрытым окном, задачей Планировщика Manta-Anchor
# (scripts/autostart-install.ps1). Вручную изнутри WSL:
#
#     make wsl-anchor          # поднять, если ещё не поднят
#     make wsl-anchor-status   # проверить
#     make wsl-anchor-stop     # снять
#
# ПОЧЕМУ НЕ systemd. Он решил бы задачу глубже (юниты, автоперезапуск,
# журнал), но это переезд всего стека с nohup на юниты — отдельная работа
# с отдельными рисками. Здесь закрывается ровно заявленная дыра: окно
# можно закрыть на крестик.
set -euo pipefail

LOG_DIR="${MANTA_LOG_DIR:-$HOME/manta-logs}"
LOG="$LOG_DIR/wsl-anchor.log"
PIDFILE="$LOG_DIR/wsl-anchor.pid"
LOCKFILE="$LOG_DIR/wsl-anchor.lock"
# Метка в argv[0] — чтобы якорь был виден в `ps -o args` как
# «manta-anchor», а не как безымянный bash.
#
# Именно args, а не comm: `exec -a` подменяет только argv[0], а comm
# остаётся «bash», потому что берётся от исполняемого файла. Поэтому
# искать якорь надо по cmdline (как это делает anchor_pid) — `ps -eo comm
# | grep manta-anchor` не найдёт его никогда.
TAG="manta-anchor"
# Сколько ждать смерти якоря после SIGTERM, прежде чем добить SIGKILL.
STOP_GRACE_S="${MANTA_ANCHOR_STOP_GRACE_S:-5}"

mkdir -p "$LOG_DIR"

say() { printf '%s %s\n' "$(date '+%F %T')" "$1" >>"$LOG"; }

# Живость определяется по pidfile, а НЕ через `pgrep -f manta-anchor`.
# pgrep по полной командной строке находит любой процесс, который метку
# просто УПОМИНАЕТ: собственный `ps | grep` оператора, строку задачи
# Планировщика, вызов make. Первая версия этой проверки именно так и
# ошибалась — считала якорь поднятым, когда его не было, и молча ничего
# не запускала.
anchor_pid() {
    local pid
    [ -r "$PIDFILE" ] || return 1
    pid=$(cat "$PIDFILE" 2>/dev/null) || return 1
    [ -n "${pid//[!0-9]/}" ] && [ "$pid" = "${pid//[!0-9]/}" ] || return 1
    [ -d "/proc/$pid" ] || return 1
    # Проверяем, что под этим pid именно наш якорь, а не случайный процесс,
    # переиспользовавший номер после перезагрузки WSL.
    tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null | grep -q "$TAG" || return 1
    printf '%s\n' "$pid"
}

case "${1:-run}" in
status)
    if pid=$(anchor_pid); then
        echo "якорь WSL: работает (pid $pid)"
        echo "окно терминала можно закрывать на крестик"
    else
        echo "якорь WSL: НЕ работает"
        echo "закрытие последнего окна WSL погасит дистрибутив вместе со стеком"
        echo "лечение: make wsl-anchor"
        exit 1
    fi
    ;;
stop)
    if pid=$(anchor_pid); then
        kill "$pid" 2>/dev/null || true
        # Смерть ПРОВЕРЯЕТСЯ, а не предполагается. Первая версия печатала
        # «якорь снят» сразу после kill и стирала pidfile — а якорь при
        # этом оставался жить. Так и было: тело якоря было
        # `trap ... TERM; while true; do sleep 3600; done`, а bash не
        # выполняет обработчик, пока не завершится текущая команда
        # переднего плана. То есть SIGTERM ждал конца часового sleep, и
        # каждый цикл «снял — поднял» оставлял в системе лишний процесс,
        # невидимый для status, потому что pidfile уже стёрт.
        # Ждём по той же проверке, что и anchor_pid, а НЕ по `kill -0`:
        # `kill -0` успешен и для зомби, а зомби — это уже мёртвый якорь,
        # просто ещё не прибранный родителем. С `kill -0` остановка честно
        # выжидала весь запас времени по каждому вызову и лишь потом слала
        # KILL трупу.
        for _ in $(seq "$((STOP_GRACE_S * 5))"); do
            anchor_pid >/dev/null || break
            sleep 0.2
        done
        if anchor_pid >/dev/null; then
            kill -9 "$pid" 2>/dev/null || true
            say "якорь не ответил на TERM, добит KILL (pid $pid)"
        fi
        rm -f "$PIDFILE"
        say "якорь снят (pid $pid)"
        echo "якорь снят (pid $pid)"
    else
        echo "якорь и так не работает"
    fi
    ;;
run)
    # flock, а не только проверка pidfile: задача Планировщика повторяется
    # по расписанию, и два срабатывания могли совпасть между проверкой и
    # записью pid. Второй экземпляр не вреден, но он мусор в ps, а мусор в
    # диагностике стоит дорого.
    exec 9>"$LOCKFILE"
    if ! flock -n 9; then
        exit 0
    fi
    # Уже поднят — выходим МОЛЧА и с нулевым кодом: холостое срабатывание
    # задачи это норма (самолечение после `wsl --shutdown`), а не ошибка.
    if anchor_pid >/dev/null; then
        exit 0
    fi
    say "якорь поднят (pid $$)"
    printf '%s\n' "$$" >"$PIDFILE"
    # exec сохраняет PID, поэтому записанный выше $$ остаётся верным.
    # exec -a подменяет argv[0] на метку.
    #
    # Тело якоря — голый `sleep infinity`, БЕЗ обёртки в bash с trap.
    # Обёртка выглядела аккуратнее, но именно она и ломала остановку:
    # обработчик сигнала в bash ждёт завершения текущей команды, поэтому
    # SIGTERM доходил до якоря только через час. У `sleep` же обработчика
    # нет вовсе, и SIGTERM убивает его действием по умолчанию — сразу.
    exec -a "$TAG" sleep infinity
    ;;
*)
    echo "использование: $0 [run|status|stop]" >&2
    exit 2
    ;;
esac
