#!/usr/bin/env bash
# Порция солей у Game Coordinator по расписанию (спринт 173).
#
#     ./scripts/gc-salts.sh            # одна порция
#     make gc-salts                    # то же самое
#
# ЗАЧЕМ РАСПИСАНИЕ, А НЕ ДЛИННЫЙ ПРОГОН. Бюджет аккаунта Steam
# НАКОПИТЕЛЬНЫЙ (замеры 2026-09-01, docs/HANDOFF.md): первые 200 запросов
# прошли подряд, потому что накопитель был полон за месяцы простоя, а
# дальше аккаунт отдавал около 0.3 соли в минуту. Прогон с паузой в
# десять секунд — вдесятеро медленнее удачного — сломался на первом же
# запросе, так что дело не в темпе. Значит помогает не «спрашивать
# медленнее», а спрашивать МЕНЬШЕ и чаще: маленькая порция раз в час
# берёт накопленное, не опустошая его залпом.
#
# ЧЕМ ЭТОТ СКРИПТ ОТЛИЧАЕТСЯ ОТ `node gc-salts.mjs`. Тем, что он про
# РАСПИСАНИЕ, а не про GC: cron гоняет его вслепую, и всё, что он умеет
# сказать, он должен сказать сам.
#
# ГЛАВНОЕ ПРАВИЛО: МОЛЧАНИЕ GC — НЕ ПОВОД ДЛЯ ТРЕВОГИ.
#
# GC не отказывает словами, он перестаёт отвечать. На исчерпанном бюджете
# это ШТАТНОЕ состояние — оно наступает каждую ночь и означает «на
# сегодня всё». Алерт здесь был бы ежесуточной ложной тревогой, а ложная
# тревога по расписанию обучает не читать канал: ровно так в этом проекте
# тринадцать дней никто не замечал, что бэкап не снимается (спринты 142,
# 163). Поэтому пустая или короткая порция — успех, а не отказ.
#
# А ВОТ ЧТО ТРЕВОГА. Всё, из-за чего соли не будет ни сегодня, ни завтра
# и что чинится только руками: нет токена, не поднялась сессия Steam,
# недоступна база. Разница между «сегодня больше нечего брать» и «добыча
# сломалась» — единственное, ради чего эта обёртка существует.
set -uo pipefail
cd "$(dirname "$0")/.."

TRAIN_ENV="${MANTA_TRAIN_ENV:-$HOME/manta-train.env}"
[ -f "$TRAIN_ENV" ] && { set -a; . "$TRAIN_ENV"; set +a; }

tg() {
    [ -n "${TELEGRAM_BOT_TOKEN:-}" ] || return 0
    curl -s --max-time 15 \
        "https://api.telegram.org/bot$TELEGRAM_BOT_TOKEN/sendMessage" \
        -d "chat_id=${TELEGRAM_CHAT_ID:-}" -d "parse_mode=HTML" \
        --data-urlencode "text=$1" >/dev/null || true
}

die() { echo "СОЛИ НЕ ДОБЫВАЮТСЯ: $1" >&2; tg "🔴 <b>Manta</b>: соли GC — $1"; exit 1; }

# «Добыча не настроена» — это КОНФИГУРАЦИЯ, а не поломка. Токен заводится
# вручную (make gc-token, нужен пароль бота), и на машине, где его не
# заводили, добыча просто не включена. Красный алерт каждый час сказал бы
# о нашем же решении её не включать.
skip() { echo "Добыча солей не настроена: $1"; exit 0; }

STATE_DIR="${GC_STATE_DIR:-$HOME/.manta-gc}"

[ -f "$STATE_DIR/refresh-token" ] || \
    skip "нет $STATE_DIR/refresh-token — добыча не включена (make gc-token)"

# Ниже этой черты добыча ОБЪЯВЛЕНА: токен на месте, значит солей ждут.
# Всё, что мешает их взять, — настоящая поломка. «Выключено» и
# «настроено, но не работает» обязаны различаться: во втором случае
# реплеи тихо перестают доезжать, а выглядит всё зелёным.
command -v node >/dev/null || die "node не установлен"

# Проверяется НАЛИЧИЕ МОДУЛЕЙ, а не каталога node_modules.
#
# Каталог есть на любой машине, где хоть раз делали `make gc-node`, — а
# зависимости с тех пор могли прибавиться (так и вышло в спринте 173:
# наполнителю понадобился `pg`). Node падает на `require` кодом 1,
# неотличимым от нашего «сессия не поднялась», и обёртка отрапортовала бы
# про Steam о беде, до Steam не дошедшей: диагноз увёл бы чинить чужое.
#
# Список берётся ИЗ package.json, а не переписывается сюда: рукописный
# перечень зависимостей разъедется при первой же новой, и разъедется
# молча.
missing=$(node -e '
  const pkg = require("./scripts/gc-node/package.json");
  const paths = ["./scripts/gc-node/node_modules"];
  const out = [];
  for (const m of Object.keys(pkg.dependencies || {})) {
    try { require.resolve(m, { paths }); } catch { out.push(m); }
  }
  process.stdout.write(out.join(" "));
' 2>/dev/null) || die "не прочитать scripts/gc-node/package.json"
[ -z "$missing" ] || die "не установлены модули Node ($missing) — make gc-node"

echo "=================================================================="
echo "  Соли Game Coordinator: порция ${GC_SALTS_PER_RUN:-8}"
echo "=================================================================="

node scripts/gc-node/gc-salts.mjs
rc=$?

# Коды разделены В САМОМ наполнителе и здесь только переводятся в тревогу
# или её отсутствие:
#   0 — порция отработала (в том числе «GC замолчал, бюджет на сегодня»);
#   1 — сессия не поднялась: чинить руками;
#   2 — нет токена или базы: чинить руками.
case "$rc" in
    0) echo "порция закончена" ;;
    1) die "сессия Steam не поднялась — GC не прислал ClientWelcome" ;;
    2) die "наполнителю не с чем работать (токен или Postgres)" ;;
    *) die "наполнитель завершился с кодом $rc" ;;
esac
