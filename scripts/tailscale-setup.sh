#!/usr/bin/env bash
# Частный доступ к Manta без домена и открытых портов (спринт 198).
#
#     ./scripts/tailscale-setup.sh            # установить и подключить
#     ./scripts/tailscale-setup.sh --check    # только проверить состояние
#
# ЗАЧЕМ ИМЕННО ТАК. Владельцу нужен круглосуточный доступ к метрикам и
# API — с ноутбука и с телефона, — но НЕ публичный сайт. Это разные
# задачи, и решать вторую средствами первой дорого: домен, A-записи,
# сертификат с продлением, basic-auth, вынесенный наружу порт. Каждая из
# этих вещей может протухнуть, и каждая расширяет то, что видно из
# интернета.
#
# Tailscale не открывает НИЧЕГО. Машина и устройства владельца получают
# адреса в частной сети, всё остальное остаётся закрытым. Сертификаты не
# нужны, потому что нет публичного имени; пароль не нужен, потому что в
# сети нет посторонних.
#
# ТОКЕН ЗДЕСЬ НЕ ХРАНИТСЯ. `tailscale up` печатает ссылку, по которой
# машину подтверждают браузером один раз. Ключ авторизации (--authkey)
# СОЗНАТЕЛЬНО не используется: он password-equivalent, и записать его в
# скрипт, историю команд или env-файл значило бы завести ещё один секрет
# ради разовой операции. Ссылка живёт минуты и одноразова.
#
# ЧЕГО СКРИПТ НЕ ДЕЛАЕТ. Не закрывает порты и не трогает ufw: это
# отдельное решение с риском отрезать себе ssh, и принимать его надо
# глядя на живую машину, а не в скрипте установки.
set -euo pipefail

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

red()  { printf '\033[31mFAIL\033[0m %s\n' "$1"; }
warn() { printf '\033[33mWARN\033[0m %s\n' "$1"; }
ok()   { printf '\033[32m OK \033[0m %s\n' "$1"; }

# -- состояние -----------------------------------------------------------------

installed() { command -v tailscale >/dev/null 2>&1; }

# Подключены ли мы к сети. Спрашиваем у самого tailscale, а не по факту
# запущенного демона: демон может работать и при вылогиненной машине, и
# тогда «сервис поднят» означало бы доступ, которого нет.
connected() {
    tailscale status --json 2>/dev/null | grep -q '"BackendState": *"Running"'
}

self_ip() { tailscale ip -4 2>/dev/null | head -1; }

report() {
    if ! installed; then
        red "tailscale не установлен"
        return 1
    fi
    ok "tailscale установлен: $(tailscale version 2>/dev/null | head -1)"
    if ! connected; then
        red "машина не подключена к сети — выполни: sudo tailscale up"
        return 1
    fi
    local ip; ip=$(self_ip)
    ok "подключено, адрес в сети: ${ip:-неизвестен}"

    # Что именно станет доступно. Печатаем адресами, а не словами:
    # владелец копирует строку в браузер, а не собирает её сам.
    if [ -n "$ip" ]; then
        echo
        echo "  публичный API (для фронта):  http://$ip:8081/api/v1/matches"
        echo "  состояние сбора (админ):     http://$ip:8080/api/v1/admin/status"
        echo "  дашборд:                     http://$ip:9107"
        echo "  Grafana:                     http://$ip:3000"
        echo
        echo "  Порты слушают 127.0.0.1 (наложение docker-compose.vps.yml),"
        echo "  поэтому из интернета они по-прежнему не видны, а из частной"
        echo "  сети — да. Если адрес не отвечает, смотри runbooks.md, п.8."
    fi
    return 0
}

if [ "$CHECK_ONLY" = 1 ]; then
    report
    exit $?
fi

# -- установка -----------------------------------------------------------------

if installed; then
    ok "tailscale уже установлен — пропускаю установку"
else
    echo ">> установка tailscale"
    # Официальный установщик: он же определяет дистрибутив и заводит
    # systemd-юнит. Своя сборка пакета здесь была бы лишней работой с
    # тем же результатом.
    curl -fsSL https://tailscale.com/install.sh | sh
fi

if connected; then
    ok "машина уже подключена — повторный вход не нужен"
else
    echo
    echo ">> сейчас будет напечатана ссылка. Открой её в браузере и"
    echo ">> подтверди машину — это делается ОДИН раз."
    echo
    # --ssh НЕ включаем: у нас уже есть ssh на 2222, и второй путь входа
    # это второй путь входа, а не удобство.
    sudo tailscale up --hostname=manta-vps
fi

echo
report
