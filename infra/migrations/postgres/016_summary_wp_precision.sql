-- Миграция 016: вероятность в карточке — double precision (спринт 192b).
--
-- ЖИВОЙ ОТКАЗ, видимый в первом же ответе публичного API:
--
--     "final_radiant_wp": 0.9961000084877014
--
-- Записали 0.9961. Колонка объявлена как REAL (float4) — около семи
-- значащих цифр, — и при расширении до float64 на выдаче вылезает хвост
-- двоичного представления. Ошибки нет, падения нет: просто число, которое
-- фронтенд покажет как «99.61000084877014 %».
--
-- ПОЧЕМУ ЧИНИМ В СХЕМЕ, А НЕ ОКРУГЛЕНИЕМ НА ВЫДАЧЕ. Округление в
-- обработчике убирает симптом там, где на него посмотрели, и оставляет
-- испорченное значение в базе — а значит следующий потребитель (экспорт,
-- отчёт, вторая версия API) встретит тот же хвост и допишет своё
-- округление. Точность теряется ОДИН раз, при записи, и чинить это надо
-- там же.
--
-- Расширение типа безопасно и не переписывает данные логически: старые
-- значения останутся такими, какими были записаны в float4 (хвост у них
-- уже есть), новые лягут точно. Пересчитывать старые карточки не нужно —
-- их перепишет ближайшая перегенерация отчёта или бэкфилл с --all.

BEGIN;

ALTER TABLE MatchSummaries
    ALTER COLUMN final_radiant_wp TYPE DOUBLE PRECISION;

COMMIT;
