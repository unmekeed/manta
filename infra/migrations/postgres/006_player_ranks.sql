-- Миграция 006: кэш рангов по account_id (спринт 123).
--
-- Зачем. Ранг — свойство ИГРОКА, а не матча, и меняется он неделями.
-- Сейчас мы тратим один запрос STRATZ на каждый матч, чтобы узнать его
-- средний ранг, и выбрасываем 95% ответов как «low-rank». Это плата за
-- одноразовое знание: тот же игрок завтра сыграет ещё десять матчей, и
-- мы заплатим за него ещё десять раз.
--
-- Кэш переворачивает экономику: платим за игрока ОДИН раз, и все его
-- будущие матчи распознаются бесплатно. Суточная квота STRATZ (15000
-- запросов) превращается из расходника в накопитель.
--
-- Ключ — account_id (он же steamAccountId у STRATZ, он же младшие 32
-- бита SteamID64). Valve отдаёт его в GetMatchHistoryBySequenceNum
-- бесплатно и пачками по 100 матчей, то есть по 1000 аккаунтов за один
-- вызов.

BEGIN;

CREATE TABLE PlayerRanks (
    account_id  BIGINT PRIMARY KEY,

    -- Шкала rank_tier: тир*10 + звезда (80+ = Immortal). Три РАЗНЫХ
    -- состояния, и различать их обязательно:
    --   NULL — аккаунт встречен в потоке, но мы его ещё не спрашивали;
    --   0    — спросили, ранга нет (закрытый профиль, нет калибровки);
    --   1..* — спросили, ранг известен.
    -- Если слить NULL и 0 в одно, закрытые профили будут вечно крутиться
    -- в очереди на опрос и съедать всю квоту — ровно тот механизм, что
    -- задушил STRATZ в спринте 87.
    rank_tier   SMALLINT,

    -- Кто ответил: stratz | opendota. Нужно не для отчётности, а чтобы
    -- при расхождении шкал (а они уже расходились: rank vs actualRank)
    -- можно было пересчитать только пострадавший срез.
    source      VARCHAR(16),

    -- Сколько раз аккаунт встретился в потоке. Это ПРИОРИТЕТ опроса, и
    -- он важнее, чем кажется: аккаунтов в потоке миллионы, а квоты —
    -- тысячи в день. Опросить случайного игрока почти бесполезно, он
    -- может не сыграть больше ни разу; опросить того, кто попадается
    -- каждый час, — значит бесплатно распознавать его матчи всегда.
    seen_count  INT NOT NULL DEFAULT 1,
    seen_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    checked_at  TIMESTAMPTZ
);

-- Очередь на первый опрос: самые частые вперёд. Частичный индекс, а не
-- обычный — строк без checked_at будет на порядки больше, чем опрошенных,
-- и полный индекс по seen_count тратил бы место на то, что уже не нужно.
CREATE INDEX playerranks_pending_idx
    ON PlayerRanks (seen_count DESC) WHERE checked_at IS NULL;

-- Очередь на ОБНОВЛЕНИЕ: самые давно проверенные вперёд.
CREATE INDEX playerranks_stale_idx
    ON PlayerRanks (checked_at) WHERE checked_at IS NOT NULL;

-- Права. ALTER DEFAULT PRIVILEGES из миграции 005 раздаёт будущим
-- таблицам только SELECT, поэтому запись коллектору нужно выдать явно —
-- без этой строки на стенде с раздельными ролями кэш молча не наполнялся
-- бы (роль есть, таблица есть, INSERT запрещён).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'manta_collector') THEN
        GRANT INSERT, UPDATE, DELETE ON PlayerRanks TO manta_collector;
    END IF;
END
$$;

COMMIT;
