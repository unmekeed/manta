-- Миграция 014: соли реплеев, добытые у Game Coordinator (спринт 171).
--
-- ЗАЧЕМ. Соль реплея не отдаёт ни один эндпоинт Web API — её знает только
-- Game Coordinator. Поэтому сегодня за каждый реплей мы платим один вызов
-- OpenDota (`/matches/{id}`) из 2000 в сутки на весь проект, и купить
-- больше нельзя: платный тариф требует карты, недоступной владельцу.
--
-- Замеры 2026-09-01 показали, что GC отдаёт соли и они работают: десять
-- из десяти проверенных скачались с CDN. Но бюджет у аккаунта скромный и
-- НАКОПИТЕЛЬНЫЙ, а не частотный: первые 200 запросов прошли подряд
-- (накопитель, полный за месяцы простоя), после чего аккаунт стал
-- отдавать примерно по 0.3 в минуту. Прогон с паузой в десять секунд —
-- вдесятеро медленнее удачного — сломался на первом же запросе, так что
-- дело не в темпе.
--
-- Порядок величины: 200–400 солей в сутки на аккаунт. Для проекта этого
-- достаточно с запасом, потому что узкое место реплейного пути не соли, а
-- ТРАФИК: 58 МиБ на матч, то есть двести реплеев — это 11 ГБ.
--
-- ПОЧЕМУ ТАБЛИЦА, А НЕ ВЫЗОВ. Добытчик солей написан на Node (питоновская
-- библиотека Steam мертва — см. docs/HANDOFF.md), а коллекторы на Python.
-- Таблица — интерфейс между ними, ровно как ReplayCandidates между
-- отбором и скачиванием. Плюс она делает работу НАКОПИТЕЛЬНОЙ: соль,
-- добытая ночью, ждёт скачивания сколько нужно, и суточный бюджет GC
-- расходуется ровно, а не залпом под сборку.

BEGIN;

CREATE TABLE IF NOT EXISTS ReplaySalts (
    match_id  BIGINT PRIMARY KEY,

    -- Кластер Valve: часть адреса реплея. Хранится отдельно, потому что
    -- по нему видно достижимость: 4xx — китайские, до них нет маршрута
    -- ни с VPS, ни из дома (проверено в спринте 153, 141 матч припаркован
    -- именно оттуда). Скачивать такие не надо, а знать про них — надо.
    cluster   INT NOT NULL,

    -- Соль. В protobuf это fixed32 БЕЗ знака, то есть до 4 294 967 295, и
    -- в INT (до 2 147 483 647) она не помещается. BIGINT — не запас на
    -- будущее, а необходимость: половина солей иначе переполнилась бы.
    salt      BIGINT NOT NULL,

    -- Откуда взяли. Сейчас всегда gc, но соль умеет отдавать и OpenDota
    -- (в составе /matches/{id}), и различать источники придётся, если
    -- окажется, что они расходятся.
    source    VARCHAR(16) NOT NULL DEFAULT 'gc',
    found_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Очередь на скачивание читается по свежести: реплеи Valve хранит около
-- двух недель, и старая соль бесполезна — файла за ней уже нет.
CREATE INDEX IF NOT EXISTS replaysalts_fresh_idx ON ReplaySalts (found_at DESC);

-- Права. ALTER DEFAULT PRIVILEGES из миграции 005 раздаёт будущим
-- таблицам только SELECT, поэтому запись нужно выдать явно — без этой
-- строки на стенде с раздельными ролями таблица молча не наполнялась бы:
-- роль есть, таблица есть, INSERT запрещён.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'manta_collector') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON ReplaySalts TO manta_collector;
    END IF;
END
$$;

COMMIT;
