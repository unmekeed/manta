-- Миграция 011: суточный бюджет вызовов OpenDota по источникам.
--
-- Квота OpenDota — 2000 запросов в сутки на IP, и купить больше нельзя
-- (платный тариф требует карты, недоступной владельцу). Это ЖЁСТКИЙ
-- потолок и самый дефицитный ресурс проекта.
--
-- До сих пор он делился по принципу «кто успел». 2026-08-06 это стоило
-- шести часов простоя ВСЕГО сбора: новый конвейер кандидатов выел квоту
-- (~2300 запросов в сутки при лимите 2000), и следом легли все остальные
-- коллекторы, включая те, что кормят про-эталон промоушен-гейта.
--
-- Считаем по дню UTC — ровно та же граница, на которой OpenDota сбрасывает
-- свой счётчик, так что таблица обнуляется сама и чистить её не нужно.
--
-- Почему в БД, а не в памяти процесса: каждый коллектор — отдельный
-- процесс, и общий лимит невозможно соблюдать поодиночке. Плюс
-- перезапуск процесса не должен обнулять потраченное.

BEGIN;

CREATE TABLE ApiBudget (
    day     DATE        NOT NULL,
    api     VARCHAR(16) NOT NULL,   -- opendota | (на будущее: stratz, steam)
    source  VARCHAR(32) NOT NULL,   -- имя коллектора
    calls   INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (day, api, source)
);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'manta_collector') THEN
        GRANT INSERT, UPDATE, DELETE ON ApiBudget TO manta_collector;
    END IF;
END
$$;

COMMIT;
