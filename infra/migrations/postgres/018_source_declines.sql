-- Миграция 018: матчи, которые источник забрал и не смог (спринт 204).
--
-- ЗАМЕР 08.09.2026, три цикла подряд:
--
--     кандидатов 380: доля STRATZ 201, не смог 140 (70%)
--     кандидатов 399: доля STRATZ 208, не смог 148 (71%)
--     кандидатов 333: доля STRATZ 160, не смог 108 (68%)
--
-- Итого 36% ВСЕГО публичного потока не собирает никто. Это не поломка, а
-- следствие устройства деления.
--
-- ПОЧЕМУ ТАК ВЫХОДИТ. Кандидаты берутся из листинга OpenDota, и делятся
-- пополам между двумя источниками деталей. Но источники НЕ РАВНОСИЛЬНЫ на
-- этих кандидатах: OpenDota может отдать детали любого матча из своего же
-- листинга, а STRATZ — только тех, которые успел разобрать у себя, то
-- есть примерно трети. Деление исходит из того, что половины
-- взаимозаменяемы; они не взаимозаменяемы.
--
-- Матч, который STRATZ забрал и не смог, до OpenDota не доходит НИКОГДА:
-- фильтр доли отсёк его ещё до запроса деталей.
--
-- ЧТО ДЕЛАЕТ ЭТА ТАБЛИЦА. Даёт источникам общую память об отказах.
-- Отказавшийся публикует match_id; напарник видит его и берёт сверх своей
-- доли. Ровно та же мысль, что в PartnerSplit (спринт 196) — доля не
-- держится за тем, кто не может собирать, — но поштучно, а не оптом.
--
-- ВТОРАЯ ПРИЧИНА ЗАВЕСТИ ЕЁ. Память об отказах жила в СЛОВАРЕ ПРОЦЕССА
-- (`_pending`, `_rejected` в stratz.py). Любой перезапуск контейнера
-- стирал её, и все отвергнутые матчи спрашивались заново — по три
-- попытки каждый. 8 сентября контейнеры пересоздавались шесть раз за
-- день.

BEGIN;

CREATE TABLE IF NOT EXISTS SourceDeclines (
    match_id    BIGINT      NOT NULL,
    source_name VARCHAR(50) NOT NULL,

    -- Почему не смог. Отказы бывают разной природы, и лечатся они
    -- по-разному: «нет матча» у STRATZ временно и лечится ожиданием,
    -- «нет рядов» тоже, а «фильтр» постоянен и напарнику ничего не
    -- сулит. Без причины таблица отвечала бы на вопрос «сколько», не
    -- отвечая на «почему», — и первый же разбор начался бы с логов.
    reason      VARCHAR(32) NOT NULL,

    -- Сколько раз пробовали до того, как сдались. Ноль попыток и три —
    -- разные утверждения о матче.
    attempts    SMALLINT    NOT NULL DEFAULT 1,
    declined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (match_id, source_name)
);

-- Напарник спрашивает «что отвергнуто за последние N часов» — то есть
-- окно по времени внутри одного источника.
CREATE INDEX IF NOT EXISTS idx_sourcedeclines_recent
    ON SourceDeclines (source_name, declined_at DESC);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'manta_collector') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON SourceDeclines
            TO manta_collector;
    END IF;
END
$$;

COMMIT;
