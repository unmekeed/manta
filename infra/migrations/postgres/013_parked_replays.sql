BEGIN;

-- Спринт 153: недостижимый реплей паркуется, а не теряется.
--
-- ЧТО СЛУЧИЛОСЬ. The International 2026 играется на китайском кластере
-- Valve, и одиннадцать из двенадцати последних про-матчей раздаются с
-- replay413.dota2.com.cn. Ни VPS в Ирландии, ни домашняя машина до него
-- не доходят — проверено с обеих, соединение просто истекает.
--
-- Коллектор при этом вёл себя ровно так, как ему велели в спринте 118:
-- три попытки, потом «сдвигаю курсор, чтобы не блокировать очередь».
-- Правило верное — вставший курсор в 2026-07-31 стоил 82 часов простоя, —
-- но у него есть цена, которую до сих пор никто не назвал: курсор
-- монотонный, и сдвинутый матч не вернётся НИКОГДА. Появись маршрут
-- завтра, реплеи TI всё равно потеряны.
--
-- ЧТО ЗДЕСЬ. Список желаний: матчи, чей реплей мы хотели и не смогли
-- взять. Очередь по-прежнему не блокируется — курсор двигается, — но
-- запись остаётся, и `--source parked` возвращается к ней, когда маршрут
-- появится: через прокси, с другой машины или после турнира.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПОЛЕ В CollectedMatches. Там лежат
-- собранные матчи, и «собран» с «хотели, но не вышло» — разные факты.
-- Спринт 151 уже разбирался с тем, во что обходится одно имя для двух
-- фактов: реплейный путь считал JSON-матчи дубликатами и не построил ни
-- одной карты.
--
-- Строка НЕ удаляется после успеха: припаркованный матч перестаёт быть
-- желанием, когда у него появляется has_replay, и источник его просто не
-- отдаёт. Чистка — отдельным DELETE по CollectedMatches, идемпотентная и
-- необязательная. Удалять из обработчика успеха значило бы завести
-- вторую точку правды о том, что матч собран.
CREATE TABLE IF NOT EXISTS ParkedReplays (
    match_id     BIGINT PRIMARY KEY,
    replay_url   TEXT NOT NULL,
    -- Хост выделен отдельно, потому что недостижимость — свойство ХОСТА,
    -- а не матча: по нему видно, вернулся ли маршрут, одним запросом.
    host         TEXT NOT NULL,
    reason       TEXT NOT NULL,
    attempts     INT  NOT NULL DEFAULT 1,
    first_parked TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    last_parked  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS parked_replays_host ON ParkedReplays (host);

-- GRANT под условием: роли заводит миграция 005, но на машине, где её
-- ещё не прогнали (или роли отключены), безусловный GRANT оборвал бы всю
-- миграцию. Тот же приём, что в 008.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'manta_collector') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON ParkedReplays TO manta_collector;
    END IF;
END
$$;

COMMIT;
