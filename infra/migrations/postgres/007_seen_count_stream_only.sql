-- Миграция 007: seen_count считает ТОЛЬКО встречи в потоке Valve.
--
-- Дефект, найденный первым же живым посевом (спринт 124). `seen_count`
-- задуман как «сколько раз аккаунт попался в потоке» и служит двум
-- вещам: приоритету опроса и метрике «доля потока» — какую часть живого
-- потока мы уже узнаём в лицо.
--
-- Но посев из архива вставлял новые строки через INSERT без seen_count,
-- то есть с DEFAULT 1. Аккаунт, которого в потоке никто не видел,
-- получал одну «встречу». После посева 9698 аккаунтов (99% из них
-- Immortal) метрика подскочила до 31.73%, хотя в реальном потоке
-- узнаваемых Immortal было в разы меньше: числитель раздулся
-- фантомными встречами.
--
-- Лечение в коде: save() вставляет seen_count = 0 явно. Строку создаёт
-- ОТВЕТ о ранге, а ответ — не наблюдение в потоке.
--
-- Здесь чиним уже записанное. Правка приблизительная и это надо
-- сказать: аккаунт, встреченный в потоке РОВНО один раз и потом
-- накрытый посевом, неотличим от чисто архивного и тоже обнулится.
-- Цена ошибки нулевая — у таких строк checked_at уже проставлен, в
-- очередь первого опроса они не попадают вовсе, и seen_count у них
-- влияет только на строку отчёта.

BEGIN;

UPDATE PlayerRanks
   SET seen_count = 0
 WHERE source = 'opendota-json'
   AND checked_at IS NOT NULL
   AND seen_count = 1;

COMMIT;
