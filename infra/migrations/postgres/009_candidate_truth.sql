-- Миграция 009: фактический ранг отобранного матча (спринт 129).
--
-- Правило отбора берёт матч по ДВУМ известным рангам из десяти игроков.
-- Это допущение, опирающееся на однородность матчмейкинга, а не факт.
-- До сих пор проверить его было нечем: мы знали, почему матч прошёл, но
-- не знали, каким он оказался.
--
-- Источник истины бесплатен. Чтобы получить соль реплея, коллектор и так
-- запрашивает /matches/{id} у OpenDota, а в этом ответе лежит rank_tier
-- КАЖДОГО игрока. То есть фактический состав матча приезжает вместе с
-- солью и не стоит ни одного дополнительного вызова — надо просто его не
-- выбрасывать.
--
-- NULL здесь означает «не смотрели» (матч скачан до этой миграции либо
-- OpenDota рангов не отдал), а не «рангов нет»: то же различие, что и в
-- PlayerRanks, и по той же причине — иначе средняя точность считалась бы
-- по матчам, о которых мы ничего не знаем.

BEGIN;

ALTER TABLE ReplayCandidates
    ADD COLUMN true_known_ranks    SMALLINT,
    ADD COLUMN true_immortal_ranks SMALLINT,
    ADD COLUMN true_avg_rank       SMALLINT;

COMMIT;
