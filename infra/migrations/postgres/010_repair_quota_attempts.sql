-- Миграция 010: вернуть в очередь кандидатов, забракованных простоем.
--
-- Дефект спринта 126, обнаруженный живым прогоном 2026-08-06. Исчерпание
-- суточной квоты OpenDota обрабатывалось как «у ЭТОГО матча нет соли»:
-- цикл переходил к следующему кандидату и сжигал шестьдесят запросов
-- впустую («взято 60, отдано 0, нет соли 60»), а каждому кандидату
-- прибавлялась попытка. Через восемь таких циклов — два часа простоя —
-- очередь начала бы превращаться в no_salt целиком, притом что с самими
-- матчами всё в порядке.
--
-- Код исправлен (429 пробрасывается наверх, где уже есть ожидание до
-- сброса квоты). Здесь чиним уже испорченное.
--
-- Опознаём по тексту ошибки: у quota-отказов в last_error лежит «429».
-- Правка идемпотентна и безопасна: возвращаются только кандидаты,
-- отвергнутые ПО ЭТОЙ причине; скачанные (done), просроченные (expired)
-- и сбойные при скачивании (failed) не трогаются.

BEGIN;

UPDATE ReplayCandidates
   SET attempts    = 0,
       state       = 'new',
       next_try_at = NULL,
       last_error  = 'сброшено миграцией 010: простой по квоте',
       updated_at  = NOW()
 WHERE state IN ('new', 'no_salt')
   AND last_error LIKE '%429%';

COMMIT;
