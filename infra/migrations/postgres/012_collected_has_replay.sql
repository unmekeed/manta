BEGIN;

-- Спринт 151: «матч собран» — это два разных факта, а не один.
--
-- ЧТО СЛУЧИЛОСЬ. На VPS витрина росла (106 матчей), а PositionSnapshots
-- оставался пуст: ни одной тепловой карты, ни фазовой, ни поминутной.
-- Сеть тут была уже ни при чём (спринт 150 её починил) — виноват дедуп.
--
-- CollectedMatches одна на все источники, и это записано в докстроке
-- timeline_runner как достоинство: «один матч никогда не въезжает дважды,
-- каким бы путём ни пришёл». Достоинство обернулось тупиком. JSON-путь
-- быстрее и жаднее реплейного (14 матчей за 30 минут против 2 за час) и
-- разбирает те же про-матчи. Каждый такой матч попадает в
-- CollectedMatches, после чего реплейный источник видит его дубликатом и
-- пропускает НАВСЕГДА:
--
--     skip duplicate match_id=8943098449
--     skip duplicate match_id=8943142948
--     cycle done, processed=0
--
-- А у JSON-матчей координат нет в принципе. То есть карты не появились бы
-- никогда — и не из-за поломки, а по устройству. На домашней машине это не
-- всплывало: там реплейный путь набрал своё раньше, чем JSON-источники
-- вышли на нынешний темп.
--
-- ЧТО МЕНЯЕТСЯ. Дедуп становится ПО ВОЗМОЖНОСТЯМ, а не по факту сбора.
-- JSON-путь по-прежнему пропускает всё, что уже собрано любым путём:
-- реплей даёт всё, что даёт JSON, и сверх того. Реплейный путь теперь
-- пропускает только матчи, у которых реплей УЖЕ есть, и достраивает
-- остальные — витрины на ReplacingMergeTree, поэтому строки замещаются
-- более полными, а не задваиваются.
--
-- Значение для уже собранных строк берётся из replay_url: JSON-путь с
-- самого начала писал туда «json:<источник>», реплейный — настоящий
-- адрес. Другого свидетельства нет, и это ровно то, по которому пришлось
-- бы гадать вручную.
ALTER TABLE CollectedMatches
    ADD COLUMN IF NOT EXISTS has_replay BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE CollectedMatches
   SET has_replay = TRUE
 WHERE replay_url NOT LIKE 'json:%';

-- Индекс не заводится намеренно: запрос всегда идёт по первичному ключу
-- (match_id), а has_replay лишь уточняет найденную строку.

COMMIT;
