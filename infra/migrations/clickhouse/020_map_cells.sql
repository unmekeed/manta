-- Спринт 98: агрегат тепловых карт по фазам игры.
--
-- Мотив тот же, что у MatchFights (миграция 015), и он не про удобство.
-- ReplayEvents живёт 14 дней (TTL, миграция 007), PositionSnapshots
-- растёт неограниченно и дорог; реплеи Valve удаляет сама. Карта,
-- построенная запросом по сырью, через две недели строится по пустоте —
-- и заметно это станет ровно тогда, когда карта понадобится.
-- Агрегат занимает единицы килобайт на матч против сотен, живёт БЕЗ TTL
-- и копится с первого дня.
--
-- Сетка 32x32 в НОРМАЛИЗОВАННЫХ координатах: игровые единицы реплея
-- (примерно -8000..8000 по обеим осям) переводятся в номер клетки при
-- записи. Хранить сырые координаты в агрегате нельзя — тогда это не
-- агрегат; хранить в игровых единицах тоже, иначе смена системы
-- координат у поставщика молча сдвинет всю историю.
--
-- ReplacingMergeTree по полному ключу: повторный разбор того же матча
-- ЗАМЕЩАЕТ клетки, а не складывает их. SummingMergeTree здесь был бы
-- ошибкой — переразбор удвоил бы плотность, и карта врала бы тем
-- сильнее, чем чаще матч переобрабатывали.
CREATE TABLE IF NOT EXISTS manta.MatchMapCells (
    match_id    UInt64,
    -- Фазы режутся по игровому времени, а не по доле матча: 10-я минута
    -- значит одно и то же в игре на 25 и на 60 минут, а «первая треть» —
    -- нет.
    phase       Enum8('early' = 1, 'mid' = 2, 'late' = 3),
    team        UInt8,    -- 2 Radiant, 3 Dire
    kind        Enum8('presence' = 1, 'farm' = 2, 'death' = 3,
                      'ward' = 4, 'smoke' = 5, 'fight' = 6),
    gx          UInt8,    -- 0..31
    gy          UInt8,
    n           UInt32,   -- сколько попаданий в клетку
    computed_at DateTime DEFAULT now()
) ENGINE = ReplacingMergeTree(computed_at)
PARTITION BY intDiv(match_id, 1000000)
ORDER BY (match_id, phase, team, kind, gx, gy);
