-- Спринт 97: SMOKE и BUYBACK — своими именами в ReplayEvents.
--
-- Два повода.
--
-- 1. Бэйбек с трека F писался как ABILITY_CAST с inflictor='buyback' —
--    лишь бы не трогать Enum8. Маскировка стоила дороже, чем экономила:
--    событие нельзя отфильтровать запросом по типу, его не видно в схеме,
--    и при беглом чтении кода оно выглядит как отсутствующее (в спринте
--    91 я именно так и решил, и написал это в HANDOFF — неверно).
--
-- 2. Смоук не собирался вовсе. Своего значения в DOTA_COMBATLOG_TYPES у
--    него нет: он приходит как MODIFIER_ADD с именем
--    modifier_smoke_of_deceit, а модификаторы в сырой слой не писались.
--    Без него карта смоук-ганков (каталог сигналов, волна 3) строится
--    не из чего.
--
-- Расширение Enum8 значениями 7 и 8 — операция над метаданными: числа
-- существующих значений не меняются, данные не переписываются.
ALTER TABLE manta.ReplayEvents
    MODIFY COLUMN event_type Enum8('DAMAGE'=1, 'HEAL'=2, 'KILL'=3,
                                   'ABILITY_CAST'=4, 'ITEM_PURCHASE'=5,
                                   'WARD_PLACE'=6, 'BUYBACK'=7, 'SMOKE'=8);
