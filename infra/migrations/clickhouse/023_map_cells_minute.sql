-- Спринт 147: тепловые карты ПОМИНУТНО.
--
-- ЗАЧЕМ. Три фазы (миграция 020) отвечают на вопрос «где команда была в
-- середине игры», а от карты хотят другого — маршрута. Между десятой и
-- двадцать пятой минутой керри успевает пройти лес, вернуться на линию и
-- уйти в чужой лес; на карте фазы 'mid' это один общий развод пятен, из
-- которого порядок обхода не восстановить. Ползунок по минутам
-- восстанавливает именно порядок — ради него всё и затевалось.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В MatchMapCells. Минута обязана
-- войти в ключ сортировки: MatchMapCells — ReplacingMergeTree, и без
-- этого строки соседних минут схлопнулись бы в одну, то есть новая
-- колонка молча уничтожила бы то, ради чего заводится. А менять ключ
-- сортировки у таблицы с данными (ALTER … MODIFY ORDER BY) — операция с
-- оговорками про первичный ключ, которую негде проверить до боевой
-- машины. Проверять её на единственном сборщике проекта я не стал.
--
-- Есть и вторая причина, не про осторожность. У поминутных запросов
-- другой порядок обращения: «минуты с 12-й по 18-ю, любые виды» против
-- «вся фаза, один вид». minute сразу после match_id даёт диапазону
-- сплошной кусок, а в общей таблице она встала бы после phase и kind.
--
-- ПРО ОБЪЁМ. Пятнадцатикратного роста, которого ждёшь от «три корзины
-- вместо сорока», не будет: число строк ограничено не сеткой, а числом
-- исходных точек. Позиции пишутся раз в ~10 секунд на героя, то есть
-- матч даёт около 2400 замеров независимо от того, на сколько корзин их
-- разложить. Дробление лишь уменьшает число совпадений в одной клетке —
-- строк становится больше в полтора-два раза, а не в пятнадцать.
--
-- Фазовая таблица остаётся и продолжает писаться: по ней построены
-- отчёты и бэкфилл, а старые матчи в поминутную не превратить — минутной
-- разбивки в них уже нет. Считается всё ОДИН раз, поминутно; фазовые
-- строки выводятся суммированием (extractor/mapcells.py: phase_cells),
-- поэтому разойтись они не могут.
--
-- ReplacingMergeTree по полному ключу — по той же причине, что и в 020:
-- повторный разбор ЗАМЕЩАЕТ клетки, а не складывает. SummingMergeTree
-- удвоил бы плотность при переразборе, и карта врала бы тем сильнее, чем
-- чаще матч трогали.
CREATE TABLE IF NOT EXISTS manta.MatchMapCellsMinute (
    match_id    UInt64,
    -- Игровая минута: 0, 1, 2… Время до гудка (оно отрицательное)
    -- сваливается в нулевую минуту — фарма там нет по определению, а
    -- присутствие всё на фонтане.
    minute      UInt16,
    team        UInt8,    -- 2 Radiant, 3 Dire
    kind        Enum8('presence' = 1, 'farm' = 2, 'death' = 3,
                      'ward' = 4, 'smoke' = 5, 'fight' = 6,
                      'farm_core' = 7),
    gx          UInt8,    -- 0..31
    gy          UInt8,
    n           UInt32,   -- сколько попаданий в клетку
    computed_at DateTime DEFAULT now()
) ENGINE = ReplacingMergeTree(computed_at)
PARTITION BY intDiv(match_id, 1000000)
ORDER BY (match_id, minute, team, kind, gx, gy);
