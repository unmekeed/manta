-- Миграция 025: драки как события с исходом (спринт 186).
--
-- ЗАЧЕМ ОТДЕЛЬНО ОТ УБИЙСТВ И УРОНА. У модели уже есть kills_diff (все
-- убийства матча) и hero_damage_diff (весь урон, спринт 185). Драка — не
-- сумма, а СОБЫТИЕ с исходом: пять смертей, размазанных по карте за
-- десять минут, и пять смертей в одном замесе — разные игры. Первое
-- значит, что кого-то ловят поодиночке; второе — что команда проиграла
-- бой и следующие полминуты у неё нет ни одного героя на карте.
--
--   fights_won_diff   счёт выигранных драк накопительно. Выиграла
--                     сторона, потерявшая МЕНЬШЕ героев; равные потери
--                     не засчитываются никому — это размен, а не победа.
--   fight_gold_diff   разница золота, взятого В ДРАКАХ. Отделяет
--                     «выиграли бой» от «выиграли бой выгодно».
--   fight_deaths_diff смерти в драках, буквально Radiant − Dire. Знак
--                     буквальный, как у всех наших разностей.
--   since_fight_s     секунд с конца последней ЗАВЕРШЁННОЙ драки. Темп
--                     игры: минута после замеса и минута тишины на
--                     тридцатой — разные состояния при равной экономике.
--                     ЕДИНСТВЕННАЯ из четырёх, что НЕ меняет знак при
--                     зеркалировании сторон: время симметрично.
--
-- DEFAULT nan, а не 0: ноль означал бы «драк не случилось» — утверждение
-- о матче. У матчей, разобранных до этого спринта, и у пришедших
-- реплейным путём драк в данных нет, и это пропуск.

ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS fights_won_diff   Float32 DEFAULT nan;
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS fight_gold_diff   Float32 DEFAULT nan;
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS fight_deaths_diff Float32 DEFAULT nan;
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS since_fight_s     Float32 DEFAULT nan;
