-- Спринт 140: карта фарма отдельно для кор-позиций (1, 2, 3).
--
-- ЗАЧЕМ. Карта фарма, посчитанная по ВСЕЙ команде, отвечает на вопрос,
-- который никто не задаёт. Саппорты половину игры стоят на линии рядом с
-- кором и бегают по варданию — их присутствие в «безопасной зоне»
-- попадает в ту же карту и размазывает её ровно там, где она должна быть
-- острой. Читать фарм-маршруты по такой карте нельзя: лес керри и
-- маршрут саппорта с вардами сливаются в одно пятно.
--
-- ПОЧЕМУ НОВЫЙ ВИД, А НЕ ПЕРЕОПРЕДЕЛЕНИЕ 'farm'. Соблазн был: просто
-- начать считать 'farm' по корам. Но в таблице уже лежат сотни матчей,
-- посчитанных ПО ВСЕЙ КОМАНДЕ, и переопределение сделало бы одно имя
-- означающим разное в зависимости от того, когда матч разбирали. Такое
-- расхождение не падает и не видно на глаз — ровно та беда, которую
-- спринт 139 выкорчёвывал из координат карты. Старый вид остаётся как
-- есть, новый добавляется рядом, и по наличию 'farm_core' сразу видно,
-- разобран матч новой версией или старой.
--
-- ALTER безопасен: добавление значения в Enum8 не переписывает данные,
-- уже записанные значения сохраняют свои номера. Новый номер (7) взят
-- следующим свободным, а не вставлен в середину — перенумерация
-- существующих значений молча переименовала бы уже записанные строки.
ALTER TABLE manta.MatchMapCells
    MODIFY COLUMN kind Enum8('presence' = 1, 'farm' = 2, 'death' = 3,
                             'ward' = 4, 'smoke' = 5, 'fight' = 6,
                             'farm_core' = 7);
