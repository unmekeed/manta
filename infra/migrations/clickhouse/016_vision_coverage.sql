-- Волна 1 каталога, пункт 3 (спринт 90): площадь карты под обзором.
--
-- obs_wards_diff (трек F, F5) считает АКТИВНЫЕ обс-варды штуками, и это
-- не то же самое, что контроль карты: три варда, поставленные в одном
-- углу, дают тот же счётчик, что три варда, раскинутые по карте, — а
-- информации от них кратно меньше. Перекрытие радиусов счётчик не видит
-- в принципе.
--
-- vision_coverage_diff — доля площади карты, накрытая обзором Radiant,
-- минус то же для Dire. Диапазон [-1, 1], считается по КООРДИНАТАМ
-- вардов, которые уже лежат в MatchEvents (x/y у ward_obs).
--
-- Сентри сюда не входят намеренно: они дают истинное зрение, а не
-- обзор, и сложение их с обсами смешало бы две разные величины.
--
-- DEFAULT nan: у матчей STRATZ координат вардов нет вовсе, а ноль
-- означал бы «стороны видят карту одинаково» — ложный сигнал.
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS vision_coverage_diff Float32 DEFAULT nan
    AFTER obs_wards_diff;
