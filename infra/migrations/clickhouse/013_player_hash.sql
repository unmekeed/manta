-- Миграция 013: псевдоним никнейма в витрине игроков (Гл. 9.7, спринт 70).
--
-- Единственный PII платформы — игровой ник. Хранить его в аналитической
-- витрине не нужно: GDPR-операции работают «вперёд» (субъект называет ник,
-- шлюз его хеширует и ищет по хешу), а интерфейс показывает героя, если
-- имени нет. Колонка добавляется отдельно от player_name, чтобы:
--   1) режим переключался без перезаливки данных;
--   2) старые строки (хеша нет) остались доступны поиску по имени.
--
-- player_hash = HMAC-SHA256(MANTA_PII_SALT, casefold(ник))[:16 hex].
-- Соль вне git: без неё соответствие «хеш ↔ ник» невосстановимо, а голый
-- sha256 по публичному списку ников подбирался бы перебором.
ALTER TABLE manta.PlayerMatchFeatures
    ADD COLUMN IF NOT EXISTS player_hash String AFTER player_name;
