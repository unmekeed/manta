-- Волна 1 каталога, пункты 4-5 (спринт 91): резерв и мёртвое золото.
--
-- unspent_gold_diff — золото В КАРМАНЕ, а не вложенное в предметы.
-- Ресурс, который сейчас не работает: копится либо намеренно (под
-- бэйбек, под тайминг), либо по ошибке (не успели закупиться). Знак
-- вклада поэтому неочевиден, и решать его — модели.
--
-- buyback_availability — сколько героев каждой стороны МОГУТ выкупиться
-- прямо сейчас: бэйбек не на кулдауне и золота хватает. В поздней игре
-- исход решающей драки определяется именно этим, а модель до сих пор о
-- резерве не знала вовсе: buybacks_diff (F2) считает ПОТРАЧЕННЫЕ
-- бэйбеки, то есть ровно противоположное — израсходованный резерв.
-- Диапазон [-5, 5].
--
-- Обе колонки считаются из JSON OpenDota (gold_t + purchase_log +
-- buyback_log), а не из реплея, как предполагал каталог: покрытие выходит
-- 1224 матча вместо 269, и обе бэкфиллятся по всей истории.
--
-- DEFAULT nan: у матчей STRATZ поминутного золота нет, а ноль означал бы
-- «карманы пусты» и «выкупиться не может никто» — оба ложные сигналы.
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS unspent_gold_diff Float32 DEFAULT nan
    AFTER item_value_diff;

ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS buyback_availability Float32 DEFAULT nan
    AFTER buybacks_diff;
