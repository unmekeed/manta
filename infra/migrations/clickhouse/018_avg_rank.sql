-- Спринт 94: средний ранг матча в витрине.
--
-- Ярлык tier='Premium' до сих пор означал РАЗНОЕ у разных источников.
-- OpenDota отсекает матчи со средним rank_tier ниже OPENDOTA_MIN_RANK
-- (80 — Immortal), а STRATZ ранг не проверял вовсе: замер 2026-08-04
-- показал среди свежесобранных матчи с rank 44 (Legend 4) и 64
-- (Ancient 4) под тем же ярлыком. В аудите это проявлялось только
-- косвенно — расхождением Radiant WR внутри одного tier (0.556 против
-- 0.598), то есть догадкой, а не фактом.
--
-- Колонка делает популяцию ИЗМЕРИМОЙ: после неё «фильтр работает» —
-- это запрос, а не рассуждение про winrate.
--
-- Шкала — та же, что у rank_tier OpenDota и rank STRATZ: тир×10 +
-- звезда (11 Herald 1 … 80 Immortal). DEFAULT 0 = «неизвестен»:
-- нулевого ранга не существует, и путать его со значением нельзя.
-- Int16, а не Float с nan: величина целочисленная и упорядоченная,
-- сравнения с порогом должны быть точными.
ALTER TABLE manta.MatchTimelineFeatures
    ADD COLUMN IF NOT EXISTS avg_rank Int16 DEFAULT 0
    AFTER tier;
