"""Якорь гейта: планка, которая не съезжает вместе с production.

ЧТО СЛОМАНО (ROADMAP, G1). Гейт сравнивает кандидата ТОЛЬКО с текущим
production и продвигает всё, что «не значимо хуже»: Δ Brier в пределах
max(порог, σ). Планка после этого пересчитывается от новой prod. Значит,
серия ничтожных по отдельности ухудшений проходит беспрепятственно и
суммируется.

Это не гипотеза. За 07.09.2026 про-эталон production прошёл

    0.1553 → 0.1565 → 0.1565 → 0.1578

Каждый шаг — «в пределах шума» (σ≈0.0009). Сумма — +0.0025, то есть
почти втрое больше допуска, который каждый шаг проходил. Модель стала
заметно хуже, и ни один гейт этого не заметил, потому что ни один гейт
не смотрел дальше предыдущего шага.

ЧЕМ ЯКОРИТЬ — МОДЕЛЬЮ, А НЕ ЧИСЛОМ. Самое очевидное решение —
запомнить лучший Brier и сравнивать с ним — НЕВЕРНО, и разобраться в
этом важнее, чем написать код.

Brier'ы разных запусков посчитаны на РАЗНЫХ ДАННЫХ. Про-эталон
набирается `_bench_mask` перестановкой списка про-матчей, а список
растёт: приезжает новый про-матч — перестановка другая, и часть матчей
переезжает между обучением и эталоном. Сравнение сохранённого числа с
новым отвечало бы на вопрос «модель стала хуже ИЛИ выборка стала
труднее», не различая эти случаи. Ровно та ошибка, от которой честный
гейт (спринт 122) и избавлялся, когда перестал верить сохранённым
метрикам production.

Поэтому якорь — САМ АРТЕФАКТ лучшей версии. Обе модели считаются
СЕЙЧАС и на ОДНИХ данных, как кандидат с prod. Реестр хранит все
версии, а продвигавшиеся защищены от `cleanup()` навсегда, — то есть
хранить отдельно ничего не нужно, достаточно указателя.

ПОЧЕМУ ЯКОРЬ НЕ ПРОТУХАЕТ. Возражение напрашивается: чемпион трёхмесячной
давности обучен на другой мете, и держать его планкой значит запретить
модели меняться вместе с игрой. Возражение снимается тем же свойством:
чемпион оценивается на СЕГОДНЯШНЕМ holdout. Устарел он на самом деле —
кандидат его обойдёт и займёт его место. Планка держит не старую модель,
а лучший результат, показанный на актуальных данных.

КОГДА ПЛАНКА ДВИЖЕТСЯ. Только вверх и только по доказанному улучшению:
кандидат обязан быть ЗНАЧИМО лучше чемпиона (Δ ≤ −допуск), а не «не
хуже». Двигать её на ничью значило бы завести тот же храповик заново,
только с лишним шагом.

ЯКОРЬ НЕ ИМЕЕТ ПРАВА ОСТАНОВИТЬ ОБУЧЕНИЕ НАВСЕГДА. Недоступный
чемпион — отсутствие проверки, а не провал: отклонять всё, пока не
починят MinIO, значит заморозить модель на неопределённый срок из-за
беды с хранилищем. Гейт в этом случае работает как до спринта 207 и
ГОВОРИТ ОБ ЭТОМ вслух: отсутствие ≠ ноль, и «храповик не применён»
обязано выглядеть иначе, чем «храповик пройден».
"""
from __future__ import annotations

import io
import logging

logger = logging.getLogger("training.ratchet")

# Отдельный стейдж реестра. Не «production», не «staging»: указатель на
# лучшую известную версию живёт своей жизнью и переживает откаты prod.
CHAMPION_STAGE = "champion"


def stage_version(reg, name: str, stage: str) -> str | None:
    """Версия стейджа; None — стейджа нет или реестр недоступен.

    Исключение здесь означало бы, что беда с хранилищем роняет обучение
    целиком. Якорь — проверка, а не путь данных.
    """
    try:
        return reg.stage_version(name, stage)
    except Exception as exc:  # noqa: BLE001
        logger.warning("стейдж %s не прочитан: %s", stage, exc)
        return None


def champion_version(reg, name: str) -> str | None:
    """Версия-чемпион; None — якоря ещё нет или реестр недоступен."""
    return stage_version(reg, name, CHAMPION_STAGE)


def load_champion(reg, name: str, version: str | None,
                  prod_version: str | None = None
                  ) -> tuple[dict | None, str]:
    """(артефакт, пояснение) для сравнения по храповику.

    Возвращает `(None, причина)`, когда сравнивать не с чем или не
    нужно. Причина — не для порядка: по ней в объяснении гейта видно,
    ПРИМЕНЯЛСЯ ли храповик, а «не применён» обязано отличаться от
    «пройден».

    Версия передаётся, а не читается здесь: тому же значению решать,
    заводить ли якорь впервые, и прочитай его каждый сам — они разошлись
    бы ровно в тот момент, когда стейдж меняется между двумя чтениями.

    Чемпион, совпадающий с production, отдельной проверки не требует:
    кандидат уже сравнивается с prod, и второй такой же прогон стоил бы
    скачивания артефакта ради заведомо того же ответа.
    """
    if not version:
        return None, "якоря ещё нет"
    if prod_version and version == prod_version:
        return None, "якорь совпадает с production"
    try:
        import joblib

        blob, _ = reg.resolve(name, version)
        return joblib.load(io.BytesIO(blob)), ""
    except Exception as exc:  # noqa: BLE001
        # Артефакт не скачался, не прошёл проверку целостности, исчез —
        # любая из этих бед означает отсутствие проверки, а не отказ.
        logger.warning("артефакт чемпиона %s недоступен: %s", version, exc)
        return None, f"якорь {version} недоступен"


def set_champion(reg, name: str, version: str) -> bool:
    """Поднять планку. True — указатель записан.

    Неудача НЕ отменяет промоушен: планка — учёт, модель — продукт. Тот
    же порядок приоритетов, по которому карточка матча пишется после
    отчёта, а не вместо него.
    """
    try:
        reg.promote(name, version, stage=CHAMPION_STAGE)
        logger.info("планка поднята: чемпион %s", version)
        return True
    except Exception as exc:  # noqa: BLE001
        logger.warning("планка не поднята (%s): %s", version, exc)
        return False
