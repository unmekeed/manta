"""Разбиение не перетасовывается при росте датасета (спринт 213).

ЧТО БЫЛО СЛОМАНО. Эталон и валидация набирались перестановкой списка
матчей:

    matches = sorted(set(...)); rng.shuffle(matches)
    to_train = set(matches[:int(len(matches) * frac)])

Перестановка списка ДРУГОЙ ДЛИНЫ — другая целиком. Датасет растёт на
сотни матчей в сутки, поэтому эталон перетасовывался на каждом прогоне:
замер показал, что добавление ОДНОГО про-матча перебрасывает 11% эталона
в обучение и обратно, сорока — 24%.

ЧЕМ ЭТО ПЛОХО — ВИДНО НЕ СРАЗУ. Production обучалась несколько дней
назад на СВОЕЙ половине про-матчей. К сегодняшнему прогону часть тех
матчей переехала в эталон, и её меряют на том, что она запомнила.
Кандидата — нет: он обучен на сегодняшнем разбиении и эталона не видел.
Гейт систематически льстил проду.

Это не гипотеза. 9–10 сентября гейт отклонил семь кандидатов подряд, и
каждый раз картина была одна: на про-эталоне кандидат «значимо хуже», а
на свежих матчах, которых не видел НИКТО, — не хуже или лучше, пять раз
из пяти.

Побочно чинится несравнимость чисел между прогонами: у ЗАМОРОЖЕННОЙ
модели Brier эталона гулял 0.1598 → 0.1509 за два дня, потому что менялся
эталон, а не модель.

ЦЕНА РЕШЕНИЯ, названная прямо: доля больше не точная. Хэш даёт
биномиальный разброс вокруг доли (на 80 матчах валидация вышла 22 вместо
16), и удержать одновременно точный размер и устойчивость состава нельзя:
любой отбор «первых N по чему-либо» снова зависит от того, кто ещё есть в
списке.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from training.dataset import FEATURES, PRO_TIER, Dataset  # noqa: E402


def pro_ds(n: int, first: int = 1000) -> Dataset:
    """n про-матчей по две строки; id идут подряд от `first`."""
    ids = np.repeat(np.arange(first, first + n), 2)
    return Dataset(X=np.zeros((len(ids), len(FEATURES))),
                   y=np.tile([1, 0], n), groups=ids, n_matches=n,
                   tiers=np.array([PRO_TIER] * len(ids)))


def bench_of(ds: Dataset) -> set[int]:
    return set(ds.groups[ds._bench_mask()].tolist())


def valid_of(ds: Dataset) -> set[int]:
    va, _ = ds._valid_mask()
    return set(ds.groups[va].tolist())


def test_the_benchmark_membership_survives_new_matches():
    """ГЛАВНОЕ: матч, попавший в эталон, остаётся в нём.

    Иначе обучающая выборка ЛЮБОЙ прежней версии пересекается с
    сегодняшним эталоном, и гейт сравнивает модель, которая эти матчи
    видела, с моделью, которая их не видела.
    """
    base = bench_of(pro_ds(600))
    for extra in (1, 5, 13, 40, 200):
        grown = bench_of(pro_ds(600 + extra))
        old_side = {g for g in base}
        new_side = {g for g in grown if g < 1600}
        assert old_side == new_side, (
            f"+{extra} матчей — сменили сторону "
            f"{len(old_side ^ new_side)} из {len(old_side)}")


def test_the_validation_membership_survives_new_matches():
    """То же для валидации.

    Для `fresh`-оценки это обязательно: она берёт из валидации матчи
    новее всего, что видела production. Уплыви валидация — такой матч мог
    бы оказаться в обучении кандидата, и оценка «никто не видел»
    перестала бы быть верной, оставшись при этом так называться.
    """
    base = valid_of(pro_ds(600))
    grown = {g for g in valid_of(pro_ds(800)) if g < 1600}
    assert base == grown, f"уплыло {len(base ^ grown)} матчей"


def test_the_split_does_not_depend_on_which_other_matches_exist():
    """Сторона матча не зависит от соседей по датасету.

    Проверка сильнее предыдущих: там датасет РОС, здесь он другой.
    Пересечение по id обязано лечь одинаково, иначе устойчивость держалась
    бы лишь на том, что мы всегда только добавляем.
    """
    a = bench_of(pro_ds(300, first=1000))
    b = bench_of(pro_ds(300, first=1150))       # сдвинутое окно
    common = {g for g in range(1150, 1300)}
    assert (a & common) == (b & common), "разбиение зависит от состава"


def test_benchmark_and_validation_do_not_overlap():
    """Две оценки считаются на РАЗНЫХ матчах.

    Свойство наследуется (валидация набирается из `~pro`), но именно
    поэтому его легко потерять правкой: пересекись выборки, и «две
    независимые оценки» стали бы одной, показанной дважды.
    """
    ds = pro_ds(400)
    assert not (bench_of(ds) & valid_of(ds))


def test_the_share_is_close_to_the_requested_one():
    """Доля примерно та, что просили.

    Устойчивость куплена точностью размера, но не ценой смысла: съедь
    доля вдвое, эталон перестал бы представлять про-домен, а обучение
    потеряло бы половину про-матчей — молча.
    """
    ds = pro_ds(2000)
    share = len(bench_of(ds)) / 2000
    assert 0.45 <= share <= 0.55, share


def test_the_validation_share_is_close_to_the_requested_one():
    """Валидация — доля от НЕэталонных матчей, а не вырожденный остаток.

    Поймано мутацией: если дать эталону и валидации ОДНУ соль, выборки
    сцепляются — у матча, ушедшего в обучение, доля заведомо больше
    порога эталона, и под порог валидации он не попадает НИКОГДА. Тогда
    срабатывает страховка «пусто — возьми один матч», и обучение молча
    идёт с валидацией из одного матча: ранняя остановка перестаёт
    работать, а выглядит всё как обычно.

    Остальные проверки эту мутацию пережили — разбиение оставалось и
    устойчивым, и непересекающимся. Устойчивое разбиение может быть
    бессмысленным.
    """
    ds = pro_ds(2000)
    train_side = 2000 - len(bench_of(ds))
    share = len(valid_of(ds)) / train_side
    assert 0.15 <= share <= 0.25, (
        f"валидация {len(valid_of(ds))} из {train_side} обучающих матчей "
        f"— доля {share:.0%} вместо ~20%")


def test_a_small_dataset_still_has_a_benchmark():
    """На крошечной выборке эталон не пустеет.

    Хэш легко отдаёт все матчи в обучение, а пустой эталон — это молчание
    гейта: `eval_holdouts` просто не вернул бы про-оценку, и решение
    приняли бы по одной валидации, не заметив подмены.
    """
    for n in range(1, 12):
        assert bench_of(pro_ds(n)), f"{n} матчей — эталон пуст"
