"""Псевдонимизация никнеймов (Гл. 9.7, остаток находки S6 обзора).

Единственный PII в Manta — игровой никнейм. Он попадал в витрину
PlayerMatchFeatures и оттуда — в отчёты. GDPR-эндпоинты (спринт 58)
позволяли его экспортировать и стереть, но само ХРАНЕНИЕ оставалось
идентифицирующим: любой, кто получил дамп витрины, получал имена.

Решение — не хранить ник вообще, а хранить его псевдоним:

    player_hash = HMAC-SHA256(salt, casefold(nick))[:16 hex]

Почему HMAC с секретной солью, а не «просто sha256(ник)». Пространство
никнеймов маленькое и публичное: голый хеш восстанавливается перебором по
списку известных ников за минуты, то есть псевдонимизацией не является.
Соль живёт в env-файле вне git (MANTA_PII_SALT) — без неё соответствие
«хеш ↔ ник» невосстановимо, и это ровно то, чего требует GDPR ст. 4(5)
(«дополнительная информация хранится отдельно»).

Обратная таблица НЕ нужна и намеренно не заводится:
  - GDPR-экспорт и стирание работают вперёд — субъект называет ник, мы
    его хешируем и ищем по хешу;
  - интерфейсу ник не нужен: фронт и так показывает героя, если имени
    нет (`p.player_name || heroLabel(p.hero)`).
Отсутствие обратной таблицы — не упущение, а главное свойство схемы:
утекать нечему.

Режим включается MANTA_PII_MODE=pseudonymize (по умолчанию plain — как
JWT и TLS в спринте 58, стенд остаётся прежним, прод обязан включить).

ВАЖНО: алгоритм продублирован в Go (api-gateway/internal/pii) — шлюз
хеширует ник из GDPR-запроса, чтобы найти строки. Реализации обязаны
совпадать байт в байт; это проверяет кросс-языковой тест
tests/test_pseudonym.py::test_matches_go_implementation.
"""
from __future__ import annotations

import hashlib
import hmac
import os

# Длина псевдонима в hex-символах. 16 hex = 64 бита: коллизий на нашем
# масштабе (миллионы игроков) не ожидается, а строка остаётся короткой.
HASH_LEN = 16

MODE_ENV = "MANTA_PII_MODE"
SALT_ENV = "MANTA_PII_SALT"


def enabled() -> bool:
    """Включена ли псевдонимизация (иначе ник пишется как есть)."""
    return os.getenv(MODE_ENV, "plain").strip().lower() == "pseudonymize"


def salt() -> bytes:
    return os.getenv(SALT_ENV, "").encode("utf-8")


def pseudonym(nick: str, key: bytes | None = None) -> str:
    """Псевдоним никнейма. Пустой ник → пустой псевдоним (нечего скрывать).

    casefold(), а не lower(): ники бывают не только латиницей, и «Ä» и «ä»
    обязаны дать один псевдоним — иначе GDPR-запрос не найдёт свои же
    строки из-за регистра.
    """
    nick = (nick or "").strip()
    if not nick:
        return ""
    key = salt() if key is None else key
    digest = hmac.new(key, nick.casefold().encode("utf-8"),
                      hashlib.sha256).hexdigest()
    return digest[:HASH_LEN]


def apply(row: dict) -> dict:
    """Проставить player_hash и, в режиме псевдонимизации, убрать ник.

    Хеш пишется ВСЕГДА (в том числе в режиме plain): так витрина готова к
    переключению режима, а GDPR-поиск по хешу работает единообразно.
    """
    row["player_hash"] = pseudonym(row.get("player_name", ""))
    if enabled():
        row["player_name"] = ""
    return row
