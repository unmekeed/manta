// Общая подготовка тестов (спринт 148).
//
// ЗАЧЕМ. @testing-library/react сам вешает очистку DOM после каждого
// теста — но только когда видит глобальный afterEach, то есть при
// `globals: true`. У нас его нет, и деревья предыдущих тестов оставались
// в document.body. Запросы через `screen` ищут по всему телу документа, и
// второй тест начинал находить кнопки первого: «Found multiple elements».
//
// Проявилось это не как ошибка теста, а как ЛОЖНЫЙ провал верного кода —
// проверка «вкладок фаз здесь нет» падала, потому что вкладки остались от
// соседнего теста. Прежние тесты компонентов молчали, потому что искали в
// container из render, а не в screen: дыра была, просто в неё не ходили.
import { cleanup } from "@testing-library/react";
import { afterEach } from "vitest";

afterEach(cleanup);
