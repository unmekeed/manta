// Отрисовка тепловой карты пятнами, а не клетками (спринт 140).
//
// ЗАЧЕМ. Клеточная карта показывает СЕТКУ, а не плотность. Сетка 32×32 —
// это наш способ хранения, а не факт об игре: герой не «стоит в клетке»,
// он стоит в точке, и резкая граница между соседними клетками рисует
// уступ там, где в игре ничего не происходит. Читать по такой карте
// маршрут фарма трудно ровно потому, что глаз цепляется за границы
// клеток вместо формы пятна.
//
// ЧТО ЗДЕСЬ. Две чистые функции: размазать клетки в непрерывное поле и
// покрасить его. Обе без DOM и без canvas — потому и проверяются
// тестами. Canvas остаётся тонкой обёрткой в компоненте: рисовать
// пиксели умеет он, а решать, какими им быть, — этот файл.

export type Cell = [number, number, number]; // gx, gy, n

/** Гауссово ядро с ПИКОМ 1 в центре (а не с единичной суммой).
 *
 * Выбор неочевидный, поэтому по порядку. Ядро с единичной СУММОЙ
 * сохраняет массу: одиночная клетка размазывается по сотням пикселей, и
 * пик падает до тысячных долей. Такое поле красится в самый холодный
 * конец шкалы, и карта выходит ПУСТОЙ при живых данных — именно так и
 * было в первой версии, а заметно стало только на скриншоте.
 *
 * Ядро с пиком 1 даёт ровно то, что нужно шкале: одиночная клетка веса w
 * после двух свёрток даёт пик w. То есть клетка с n = maxN приходит в
 * верх шкалы сама, без обратного домножения.
 *
 * Промежуточная версия имела и нормировку суммы, и деление на пик — они
 * сокращались ровно, и мутация, убиравшая любую из них, не роняла ни
 * одного теста. Пара взаимно гасящих преобразований выглядит осмысленно
 * и не делает ничего; убрано.
 */
function kernel(radius: number, sigma: number): Float32Array {
  const size = radius * 2 + 1;
  const k = new Float32Array(size);
  for (let i = 0; i < size; i += 1) {
    const d = i - radius;
    k[i] = Math.exp(-(d * d) / (2 * sigma * sigma));
  }
  return k;
}

/** Клетки сетки grid×grid → непрерывное поле out×out, значения 0..1.
 *
 * Свёртка разделяемая (сначала по строкам, потом по столбцам): двумерное
 * ядро дало бы тот же результат за O(r²) на пиксель вместо O(r).
 *
 * ВАЖНО про ось Y: на вход приходят клетки агрегата, где (0,0) — ЮГО-
 * запад, а поле адресуется как изображение, сверху вниз. Переворот
 * делается здесь, один раз, и больше нигде — ровно как в компонентах
 * карты. Забыть его значит получить правдоподобную зеркальную карту.
 */
export function densityField(
  cells: Cell[],
  grid: number,
  out: number,
  maxN: number,
  sigmaCells = 0.9,
): Float32Array {
  const field = new Float32Array(out * out);
  if (!cells.length || maxN <= 0 || grid <= 0 || out <= 0) return field;

  const scale = out / grid;
  for (const [gx, gy, n] of cells) {
    // Центр клетки, а не её угол: иначе всё поле сдвинуто на полклетки.
    const px = Math.floor((gx + 0.5) * scale);
    const py = Math.floor((grid - 1 - gy + 0.5) * scale);
    if (px < 0 || px >= out || py < 0 || py >= out) continue;
    field[py * out + px] += n / maxN;
  }

  const sigma = Math.max(sigmaCells * scale, 0.5);
  const radius = Math.max(1, Math.ceil(sigma * 3));
  const k = kernel(radius, sigma);
  const tmp = new Float32Array(out * out);

  for (let y = 0; y < out; y += 1) {
    for (let x = 0; x < out; x += 1) {
      let acc = 0;
      for (let i = -radius; i <= radius; i += 1) {
        const sx = x + i;
        if (sx < 0 || sx >= out) continue;
        acc += field[y * out + sx] * k[i + radius];
      }
      tmp[y * out + x] = acc;
    }
  }
  // Поле НЕ перенормируется по своему максимуму, и это важнее, чем
  // кажется. Слоёв два, Radiant и Dire, а фаз три; нормировка каждого по
  // себе сделала бы одинаково яркими кипящую половину карты и пару
  // случайных заходов на чужую, а редкую фазу разожгла бы до цвета
  // плотной. Шкала должна быть общей — она приходит из maxN, посчитанного
  // на сервере внутри пары (фаза, вид).
  //
  // Скопление клеток при этом даёт больше единицы и упирается в верх
  // шкалы. Так и должно быть: это и есть очаг.
  for (let x = 0; x < out; x += 1) {
    for (let y = 0; y < out; y += 1) {
      let acc = 0;
      for (let i = -radius; i <= radius; i += 1) {
        const sy = y + i;
        if (sy < 0 || sy >= out) continue;
        acc += tmp[sy * out + x] * k[i + radius];
      }
      field[y * out + x] = acc;
    }
  }
  return field;
}

// Опорные цвета шкалы: холодный синий → бирюзовый → зелёный → жёлтый →
// красный. Это привычная «тепловая» шкала, и привычность здесь важнее
// перцептивной равномерности: карту читают, сравнивая пятна между собой
// на одной картинке, а не считывая абсолютные значения по легенде.
const STOPS: [number, number, number, number][] = [
  [0.0, 0, 60, 200],
  [0.25, 0, 190, 200],
  [0.5, 40, 210, 60],
  [0.75, 250, 220, 40],
  [1.0, 230, 30, 30],
];

/** Значение поля 0..1 → цвет RGBA. */
export function heatColor(t: number): [number, number, number, number] {
  // Number.isFinite ОБЯЗАТЕЛЕН: Math.max(NaN, 0) — это NaN, зажатие
  // само по себе NaN не ловит, и в пиксель ушло бы неопределённое
  // значение. NaN приезжает не из воздуха: клетка с испорченным n или
  // max_n = 0 в отчёте дают именно его.
  const v = Number.isFinite(t) ? Math.min(Math.max(t, 0), 1) : 0;
  let lo = STOPS[0];
  let hi = STOPS[STOPS.length - 1];
  for (let i = 0; i < STOPS.length - 1; i += 1) {
    if (v >= STOPS[i][0] && v <= STOPS[i + 1][0]) {
      lo = STOPS[i];
      hi = STOPS[i + 1];
      break;
    }
  }
  const span = hi[0] - lo[0];
  const f = span > 0 ? (v - lo[0]) / span : 0;
  const mix = (a: number, b: number) => Math.round(a + (b - a) * f);

  // Прозрачность растёт вместе со значением, и это не украшение. Пятно с
  // постоянной альфой закрасило бы подложку ровным ковром по всей карте,
  // включая места, где герой прошёл однажды, — и карта перестала бы
  // отвечать на вопрос «где он БЫЛ ЧАЩЕ».
  const alpha = Math.min(v * 2.2, 1);
  return [mix(lo[1], hi[1]), mix(lo[2], hi[2]), mix(lo[3], hi[3]), alpha];
}

/** Поле → пиксели RGBA для ImageData. */
export function fieldToPixels(field: Float32Array): Uint8ClampedArray {
  const px = new Uint8ClampedArray(field.length * 4);
  for (let i = 0; i < field.length; i += 1) {
    const [r, g, b, a] = heatColor(field[i]);
    px[i * 4] = r;
    px[i * 4 + 1] = g;
    px[i * 4 + 2] = b;
    px[i * 4 + 3] = Math.round(a * 255);
  }
  return px;
}
