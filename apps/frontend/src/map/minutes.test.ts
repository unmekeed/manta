// Тесты выбора кадра поминутной карты (спринт 148).
//
// Всё, что здесь проверяется, на картинке выглядит правдоподобно при
// любой ошибке: сдвиг на минуту, потерянная клетка, не та нормировка.
// Тепловая карта — визуализация; выцветшая или сдвинутая версия
// неотличима от настоящей, пока не сверишь с игрой.

import { describe, expect, it } from "vitest";

import {
  busyMinutes,
  frameCells,
  frameMax,
  minuteLabel,
  WHOLE_GAME,
  type MinuteCell,
} from "./minutes";

const CELLS: MinuteCell[] = [
  [0, 1, 1, 2],
  [1, 1, 1, 3],
  [1, 5, 5, 4],
  [3, 1, 1, 5],
];

describe("кадр одной минуты", () => {
  it("берёт только свою минуту и снимает с клетки номер минуты", () => {
    expect(frameCells(CELLS, 1)).toEqual([
      [1, 1, 3],
      [5, 5, 4],
    ]);
  });

  it("пустая минута — пустой кадр, а не соседняя минута", () => {
    // Сдвиг на единицу — самая правдоподобная из возможных ошибок:
    // картинка остаётся осмысленной, просто показывает не тот момент.
    expect(frameCells(CELLS, 2)).toEqual([]);
  });

  it("минута за пределами матча не роняет и не выдумывает", () => {
    expect(frameCells(CELLS, 99)).toEqual([]);
  });
});

describe("вся игра", () => {
  it("СКЛАДЫВАЕТ клетку по минутам, а не берёт последнюю", () => {
    // Клетка (1,1) встречается в минутах 0, 1 и 3: 2 + 3 + 5 = 10.
    // Возьми код последнее значение — вышло бы 5, и картинка осталась
    // бы правдоподобной, просто клетка, где герой простоял полматча,
    // сравнялась бы с той, где он был минуту.
    expect(frameCells(CELLS, WHOLE_GAME)).toEqual([
      [1, 1, 10],
      [5, 5, 4],
    ]);
  });

  it("порядок клеток устойчив", () => {
    // Map в JS сохраняет порядок вставки, то есть без явной сортировки
    // порядок зависел бы от того, как строки легли в отчёт.
    const shuffled: MinuteCell[] = [
      [2, 9, 9, 1],
      [0, 0, 0, 1],
      [1, 9, 0, 1],
    ];
    expect(frameCells(shuffled, WHOLE_GAME)).toEqual([
      [0, 0, 1],
      [9, 0, 1],
      [9, 9, 1],
    ]);
  });

  it("не путает координаты между собой", () => {
    // Клетки (3,7) и (7,3) обязаны остаться разными. Упаковка в один
    // ключ — соблазн перепутать местами, а на карте это зеркалит
    // картинку по диагонали: правдоподобно и незаметно.
    const cells: MinuteCell[] = [
      [0, 3, 7, 1],
      [0, 7, 3, 2],
    ];
    expect(frameCells(cells, WHOLE_GAME)).toEqual([
      [3, 7, 1],
      [7, 3, 2],
    ]);
  });
});

describe("нормировка", () => {
  const block = {
    max_n: 10,
    max_by_minute: [2, 4, 0, 5],
    radiant: CELLS,
    dire: [] as MinuteCell[],
  };

  it("кадр нормируется своей минутой", () => {
    expect(frameMax(block, 1)).toBe(4);
  });

  it("вся игра нормируется максимумом сумм", () => {
    // Именно 10, а не 5: максимум из поминутных занизил бы шкалу, и
    // общая карта вышла бы пересвеченной.
    expect(frameMax(block, WHOLE_GAME)).toBe(10);
  });

  it("пустая минута даёт ноль, а не последнюю известную шкалу", () => {
    expect(frameMax(block, 2)).toBe(0);
  });

  it("минута за пределами массива даёт ноль, а не undefined", () => {
    // undefined уехал бы в деление и покрасил бы карту в NaN — то есть
    // в прозрачное, неотличимое от пустого.
    expect(frameMax(block, 99)).toBe(0);
  });
});

describe("подсказка по занятым минутам", () => {
  it("перечисляет минуты, где что-то было", () => {
    const block = {
      max_n: 1,
      max_by_minute: [0, 3, 0, 0, 7],
      radiant: [] as MinuteCell[],
      dire: [] as MinuteCell[],
    };
    expect(busyMinutes(block)).toEqual([1, 4]);
  });

  it("нулевая минута не теряется", () => {
    // Классическая ловушка фильтрации по индексу: 0 ложен.
    const block = {
      max_n: 1,
      max_by_minute: [5, 0],
      radiant: [] as MinuteCell[],
      dire: [] as MinuteCell[],
    };
    expect(busyMinutes(block)).toEqual([0]);
  });
});

describe("подпись", () => {
  it("минута пишется в игровом виде", () => {
    expect(minuteLabel(0)).toBe("0:00");
    expect(minuteLabel(37)).toBe("37:00");
  });

  it("вся игра названа словами", () => {
    expect(minuteLabel(WHOLE_GAME)).toBe("вся игра");
  });
});
