// Координаты карты на стороне фронта (спринт 139).
//
// Порт libs/dota_map.py. Числа обязаны совпадать с питоновскими — их
// сверяет scripts/tests/test_map_coords_agree.py, потому что расхождение
// здесь и есть та самая беда, ради которой заводился общий модуль:
// агрегаты посчитаны по одной сетке, нарисованы по другой, и увидеть это
// можно только по кривому наложению.
//
// ПРОСТРАНСТВА. Их три, и путать их дорого:
//   мировые      что отдаёт парсер: (0,0) — центр карты, Y вверх;
//   клетки       что отдаёт OpenDota для вардов: 64..192, (0,0) — юго-запад;
//   единичные    [0,1]², (0,0) — ЮГО-ЗАПАД, база Radiant.
//
// Переворот оси Y для SVG делается ОДИН раз, в компоненте отрисовки. Если
// сделать его ещё и здесь, карта выйдет правдоподобной, но зеркальной, и
// заметить это можно только зная, где обычно фармят.

export const WORLD_HALF = 8192;
export const CELL_MIN = 64;
export const CELL_MAX = 192;
export const UNITS_PER_CELL = (2 * WORLD_HALF) / (CELL_MAX - CELL_MIN);

export function worldToUnit(x: number, y: number): [number, number] {
  return [(x + WORLD_HALF) / (2 * WORLD_HALF), (y + WORLD_HALF) / (2 * WORLD_HALF)];
}

export function cellToUnit(cx: number, cy: number): [number, number] {
  const span = CELL_MAX - CELL_MIN;
  return [(cx - CELL_MIN) / span, (cy - CELL_MIN) / span];
}

// -- калибровка подложки ------------------------------------------------------
//
// Картинка — сшитый скриншот карты 7.41 (Liquipedia, 8909×8424). Она НЕ
// квадратная и содержит не только игровую зону: по краям нарисованы
// скалы и пустота за пределами проходимой части. Поэтому подложку
// нельзя просто растянуть на весь квадрат — метки уедут.
//
// ЧТО ИЗМЕРЕНО. Центр карты найден объективно, а не на глаз. Карта Dota
// симметрична поворотом на 180°, и центр — это точка, вокруг которой
// картинка лучше всего совпадает сама с собой. Считать пришлось по
// ГРАДИЕНТУ, а не по яркости: Radiant светло-зелёный, Dire тёмно-серый,
// поворот кладёт светлое на тёмное и корреляция по яркости равна нулю.
// Геометрия при этом симметрична — её и брали.
//
// Три независимых размера окна дали один и тот же центр (0.4800, 0.5401)
// в долях исходника, и наложение картинки на саму себя, повёрнутую,
// показало реку, обе ямы Рошана и обе базы без двоения. Файл в assets/
// уже обрезан по этому центру — самый большой квадрат, который в него
// вписывается.
//
// ЧТО НЕ ИЗМЕРЕНО И ПОЧЕМУ. Масштаба в картинке НЕТ. Скриншот показывает
// и проходимую часть, и заграничные скалы, а где именно проходит ±8192,
// по пикселям не видно: содержимое доходит до самых краёв изображения,
// так что и рамка непустого не помогает. Единственный честный источник —
// собственные данные: облако реальных вардов и позиций поверх подложки.
// Поэтому ниже стоит ОЦЕНКА, а в компоненте есть режим калибровки.
//
// PLAYABLE_FRACTION — какую долю стороны квадратной картинки занимает
// проходимая карта. 0.85 получено по «колену»: рамка квадрата остаётся
// сплошным содержимым примерно до этой доли, дальше в неё начинает
// попадать пустота из углов сшивки.
export const PLAYABLE_FRACTION = 0.85;

// Подобранное значение переживает перезагрузку. Без этого калибровка
// требовала бы правки кода и пересборки на КАЖДУЮ пробу — а калибровка,
// которую больно делать, не делается, и подложка остаётся кривой.
const STORE_KEY = "manta.map.playableFraction";

export function storedFraction(): number {
  try {
    const raw = localStorage.getItem(STORE_KEY);
    const v = raw === null ? NaN : Number(raw);
    // Диапазон, а не просто «число»: 0 обратил бы масштаб в бесконечность
    // и карта исчезла бы без следа, а чинить пришлось бы через консоль.
    return v >= 0.4 && v <= 1.2 ? v : PLAYABLE_FRACTION;
  } catch {
    return PLAYABLE_FRACTION;
  }
}

export function storeFraction(v: number): void {
  try {
    localStorage.setItem(STORE_KEY, String(v));
  } catch {
    /* приватный режим — просто не запомним */
  }
}

/** Прямоугольник подложки в координатах SVG стороной S.
 *
 * Картинка рисуется БОЛЬШЕ единичного квадрата и обрезается им: игровая
 * часть занимает fraction стороны файла, значит файл надо растянуть в
 * 1/fraction раз и сдвинуть, чтобы центры совпали.
 */
export function underlayRect(S: number, fraction = PLAYABLE_FRACTION): {
  x: number; y: number; size: number;
} {
  const size = S / fraction;
  const off = (size - S) / 2;
  return { x: -off, y: -off, size };
}
