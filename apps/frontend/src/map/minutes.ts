// Выбор кадра поминутной тепловой карты (спринт 148).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Ползунок — это две операции над данными:
// «взять минуту» и «сложить все минуты». Обе чистые, обе легко
// испортить незаметно, и обе неотличимы на глаз от правильных — сдвиг на
// одну минуту, потерянная сторона, не та нормировка. В компоненте они
// проверялись бы только через рендер.
//
// ПРО НОРМИРОВКУ. Кадр одной минуты и вся игра нормируются РАЗНО, и это
// не мелочь оформления. В минуте попаданий в клетку единицы, за игру —
// сотни; общая шкала сделала бы минутные кадры почти пустыми, а пустая
// минута читается как «никто там не был». Оба максимума приходят с
// сервера уже посчитанными: считать их здесь значило бы завести вторую
// формулу для того же числа.

import type { MinuteHeatmapBlock } from "../lib/api";

// [минута, gx, gy, n] — как приходит с сервера.
export type MinuteCell = [number, number, number, number];
// [gx, gy, n] — как их ждёт HeatMap.
export type Cell = [number, number, number];

// «Вся игра» вместо конкретной минуты. Отдельное значение, а не
// undefined: ползунок и переключатель живут в одном состоянии, и
// смешивать «минута не выбрана» с «выбраны все» значило бы завести
// состояние, в котором непонятно, что показывать.
export const WHOLE_GAME = -1;

/** Клетки одной минуты (или всей игры) одной стороны. */
export function frameCells(cells: MinuteCell[], minute: number): Cell[] {
  if (minute !== WHOLE_GAME) {
    return cells.filter((c) => c[0] === minute).map((c) => [c[1], c[2], c[3]]);
  }
  // Вся игра — СУММА по клетке, а не последнее её значение: клетка, в
  // которой герой простоял десять минут, обязана быть в десять раз
  // ярче той, где он был минуту. Именно этого фазовая карта и не
  // показывала внутри своих пятнадцати минут.
  const sum = new Map<number, number>();
  for (const [, gx, gy, n] of cells) {
    const key = gx * 1024 + gy;
    sum.set(key, (sum.get(key) ?? 0) + n);
  }
  return [...sum.entries()]
    .map(([key, n]): Cell => [Math.floor(key / 1024), key % 1024, n])
    .sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}

/** Нормировка кадра: максимум внутри минуты либо за всю игру. */
export function frameMax(block: MinuteHeatmapBlock, minute: number): number {
  if (minute === WHOLE_GAME) return block.max_n;
  return block.max_by_minute[minute] ?? 0;
}

/**
 * Минуты, в которые у вида хоть что-то было.
 *
 * Нужны не для фильтрации, а для подсказки под ползунком: тащить его по
 * пятнадцати пустым минутам подряд, гадая, сломано ли что-то, — худший
 * вид молчания. Пустые минуты остаются проходимыми: их отсутствие тоже
 * факт (никто не ставил вардов), и выкидывать их из шкалы значило бы
 * растянуть время нелинейно.
 */
export function busyMinutes(block: MinuteHeatmapBlock): number[] {
  return block.max_by_minute
    .map((n, i) => (n > 0 ? i : -1))
    .filter((i) => i >= 0);
}

/** Подпись минуты в привычном игровом виде: 7 → «7:00». */
export function minuteLabel(minute: number): string {
  return minute === WHOLE_GAME ? "вся игра" : `${minute}:00`;
}
