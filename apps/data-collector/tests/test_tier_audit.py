"""Вердикты сверки `tier` с рангом (спринт 199).

Числа посчитает ClickHouse; ошибиться легче в ТРАКТОВКЕ. Три случая
выглядят похоже и лечатся по-разному:

  * ранг неизвестен — источник его не сообщает, чинится проводкой ранга;
  * ранг известен и низок — планка фильтра пропускает не то;
  * уровень высокого ранга не обещал — сверять нечего, и молчание здесь
    единственный честный ответ.

Слив их в одно «что-то не так», инструмент отправил бы человека искать
поломку вслепую — а именно от этого он и должен избавлять.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))

from tier_audit import HIGH_RANK, HIGH_TIERS, verdict  # noqa: E402


def test_the_threshold_matches_the_collector_filter():
    """Порог — тот же, что у фильтра источников, а не свой.

    Вопрос аудита ровно один: соблюдается ли обещание, которое даёт
    ярлык. Свой порог отвечал бы на другой вопрос — «нравится ли нам эта
    выборка», — и расходился бы с фильтром при первой же его правке.
    """
    assert HIGH_RANK == 80, HIGH_RANK
    assert "Premium" in HIGH_TIERS


def test_pub_is_not_accused_of_low_rank():
    """Pub низкого ранга не обещает — низкий ранг в нём норма.

    Обвинить Pub значило бы получить постоянную красную строку, к
    которой привыкают и перестают читать. Инструмент, кричащий всегда,
    молчит.
    """
    v = verdict("Pub", matches=1000, unknown=0, below=900)
    assert "сверять нечего" in v
    assert not v.startswith(("НАРУШЕНИЕ", "РАНГ"))


def test_all_ranks_unknown_is_its_own_diagnosis():
    """ГЛАВНОЕ РАЗЛИЧЕНИЕ: «не знаем» — не то же, что «низкий».

    Ровно это и было у реплейного пути до спринта 199: колонка нулевая,
    ярлык не сверяется ни с чем. Назови мы это нарушением — пошли бы
    чинить планку фильтра, которая исправна. Назови нормой — пропустили
    бы, что 85% данных не проверены вовсе.
    """
    v = verdict("Premium", matches=500, unknown=500, below=0)
    assert v.startswith("РАНГ НЕИЗВЕСТЕН"), v
    assert "не сверяется" in v


def test_a_real_violation_is_named_a_violation():
    """Известный и низкий ранг под ярлыком Premium — находка.

    Замер 2026-08-04: среди «Premium» нашлись матчи ранга 44 и 64.
    Половина высокоранговой выборки высокоранговой не была, и модель
    училась на популяции, не похожей на ту, по которой её судят.
    """
    v = verdict("Premium", matches=100, unknown=0, below=30)
    assert v.startswith("НАРУШЕНИЕ"), v
    assert "30 из 100" in v


def test_a_single_stray_match_is_not_an_alarm():
    """Один-два матча ниже порога — не повод кричать.

    Ранги на границе плавают: игрок мог откатиться между матчем и
    запросом. Порог в 10% отделяет шум от систематического перекоса —
    без него аудит краснел бы всегда и перестал бы читаться.
    """
    v = verdict("Premium", matches=100, unknown=0, below=3)
    assert not v.startswith("НАРУШЕНИЕ"), v


def test_a_verified_label_says_so_plainly():
    """Подтверждённый ярлык называется подтверждённым.

    Молчание в этом месте неотличимо от «проверка не выполнялась» — а
    это ровно та пара, которую весь спринт и разводят.
    """
    assert verdict("Premium", matches=100, unknown=0, below=0) == \
        "ярлык подтверждён наблюдаемым рангом"


def test_a_partly_unknown_population_says_what_is_unverified():
    """Частичная неизвестность названа долей, а не проигнорирована.

    Смешанный случай самый частый: часть матчей собрана до проводки
    ранга, часть после. Промолчать о непроверенной доле значит выдать
    вывод по половине данных за вывод по всем.
    """
    v = verdict("Premium", matches=100, unknown=40, below=2)
    assert "40" in v and "не проверена" in v
