"""Соли реплеев, добытые у Game Coordinator (спринт 172).

Читающая половина того, что спринт 171 научился добывать. Пишет в
таблицу `ReplaySalts` наполнитель на Node (`scripts/gc-node/gc-salts.mjs`),
читает её этот модуль.

ЧТО ЭТО МЕНЯЕТ, А ЧТО НЕТ.

Не меняет — расход квоты OpenDota, и это стоит сказать прямо, потому что
в спринте 171 я записал обратное. Соль приходит в ответе `/matches/{id}`
не одна: там же лежит `rank_tier` каждого игрока, до десяти рангов за
один вызов. Прямой путь за рангом — `/players/{account_id}`, один ранг за
вызов. Отказаться от ответа ради экономии вызова и потратить тот же вызов
на ранг — это обмен десяти рангов на один. Поэтому вызов остаётся; сбор
рангов из него слишком выгоден, чтобы его терять.

Меняет — то, от чего конвейер ЗАВИСИТ. Сегодня матч без соли у OpenDota
откладывается, а после восьми попыток закрывается как `no_salt`
навсегда. Свежий матч — ровно этот случай: OpenDota ещё не разобрала его,
а Valve хранит реплей около двух недель. GC знает соль сразу, поэтому с
ней матч уходит в скачивание не дожидаясь никого.

И главное: **исчерпанная квота перестаёт останавливать выдачу.** Квота —
самый дефицитный ресурс проекта (2000 в сутки на IP, купить нельзя), и
2026-08-06 её исчерпание положило ВЕСЬ сбор на шесть часов. Матч, соль
которого уже лежит в ReplaySalts, к OpenDota не обращается вовсе, и
конвейер продолжает работать на голодной квоте.
"""
from __future__ import annotations

import logging

logger = logging.getLogger("collector.salts")

# Адрес реплея у Valve. Собирается ровно так же, как в замере GC
# (scripts/gc-node/gc-probe.mjs), и это единственное место в Python, где
# он собирается вообще: разъехавшиеся формулы дали бы 404, неотличимый
# от «соль неверна».
REPLAY_URL = "http://replay{cluster}.valve.net/570/{match_id}_{salt}.dem.bz2"


def replay_url(match_id: int, cluster: int, salt: int) -> str:
    return REPLAY_URL.format(cluster=int(cluster), match_id=int(match_id),
                             salt=int(salt))


class SaltStore:
    """Чтение ReplaySalts. Писателя здесь нет — он на Node."""

    def __init__(self, db) -> None:
        self._db = db

    def urls_for(self, match_ids: list[int]) -> dict[int, str]:
        """{match_id -> адрес реплея} для тех, у кого соль уже добыта.

        Одним запросом на всю порцию, а не по матчу за раз: цикл
        кандидатов берёт десятки за проход, и шестьдесят обращений к базе
        ради шестидесяти целых чисел — трата на пустом месте.

        Отсутствие соли — обычное дело, а не ошибка: наполнитель успевает
        не за всеми. Поэтому возвращается словарь, а не список в порядке
        запроса: спутать «нет соли» с «соль соседнего матча» здесь
        означало бы скачать чужой файл.
        """
        if not match_ids:
            return {}
        with self._db.cursor() as cur:
            cur.execute(
                "SELECT match_id, cluster, salt FROM ReplaySalts"
                " WHERE match_id = ANY(%s)",
                ([int(m) for m in match_ids],))
            rows = cur.fetchall()
        return {int(mid): replay_url(mid, cluster, salt)
                for mid, cluster, salt in rows}
